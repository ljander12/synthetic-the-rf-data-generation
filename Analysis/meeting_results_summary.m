%% Meeting results summary
%
% Compact overview of the main quality-metric results:
%
%   A) Quantitative SWS reconstruction across stiffness contrast
%   B) Detectability metrics across stiffness contrast
%   C) Metric specificity under controlled degradation
%   D) Spatial sharpness metrics under controlled blur
%
% All values are loaded from previously saved result files.
% No metrics are recomputed here.

clear;
clc;
close all;

%% ========================================================================
% Paths
% ========================================================================

analysis_dir = fileparts(mfilename('fullpath'));
repo_dir = fileparts(analysis_dir);

results_dir = fullfile( ...
    repo_dir, ...
    'Results');

metric_summary_dir = fullfile( ...
    results_dir, ...
    'metric_summary');

stress_dir = fullfile( ...
    results_dir, ...
    'metric_stress_test');

output_dir = fullfile( ...
    results_dir, ...
    'meeting_summary');

if ~isfolder(output_dir)
    mkdir(output_dir);
end

%% ========================================================================
% Load saved results
% ========================================================================

contrast_file = fullfile( ...
    metric_summary_dir, ...
    'contrast_sweep_metric_summary.csv');

bias_file = fullfile( ...
    stress_dir, ...
    'global_bias_stress_test.csv');

noise_file = fullfile( ...
    stress_dir, ...
    'map_noise_stress_test.csv');

blur_file = fullfile( ...
    stress_dir, ...
    'spatial_blur_stress_test.csv');

sharpness_noise_file = fullfile( ...
    stress_dir, ...
    'sharpness_noise_sensitivity.csv');

required_files = { ...
    contrast_file, ...
    bias_file, ...
    noise_file, ...
    blur_file, ...
    sharpness_noise_file};

for k = 1:numel(required_files)

    if ~isfile(required_files{k})

        error( ...
            'Required result file not found:\n%s', ...
            required_files{k});

    end

end

contrast = readtable(contrast_file);
bias_test = readtable(bias_file);
noise_test = readtable(noise_file);
blur_test = readtable(blur_file);
sharp_noise = readtable(sharpness_noise_file);

%% ========================================================================
% Prepare contrast-sweep data
% ========================================================================

GT_SWS = ...
    contrast.GT_Inclusion_SWS_mps;

estimated_SWS = ...
    contrast.Estimated_Inclusion_SWS_mps;

GT_contrast = ...
    contrast.GT_Contrast_mps;

CNR_contrast = ...
    contrast.CNR;

gCNR_contrast = ...
    contrast.DirectKDE_gCNR;

case_names = ...
    string(contrast.Case);

%% ========================================================================
% Prepare normalized stress-test responses
%
% Each degradation is normalized to its OWN undegraded baseline.
%
% 1 = no change relative to baseline
% >1 = metric increased
% <1 = metric decreased
% ========================================================================

%% Global bias

idx_bias_base = ...
    find(abs(bias_test.AppliedBias_mps) < 1e-12, 1);

[~, idx_bias_stress] = ...
    max(bias_test.AppliedBias_mps);

bias_base = [ ...
    bias_test.GlobalRMSE_mps(idx_bias_base), ...
    bias_test.CNR(idx_bias_base), ...
    bias_test.DirectKDE_gCNR(idx_bias_base), ...
    bias_test.ContrastRecovery(idx_bias_base)];

bias_stress = [ ...
    bias_test.GlobalRMSE_mps(idx_bias_stress), ...
    bias_test.CNR(idx_bias_stress), ...
    bias_test.DirectKDE_gCNR(idx_bias_stress), ...
    bias_test.ContrastRecovery(idx_bias_stress)];

bias_response = ...
    bias_stress ./ bias_base;

%% Map-domain noise

idx_noise_base = ...
    find(abs(noise_test.NoiseSigma_mps) < 1e-12, 1);

[~, idx_noise_stress] = ...
    max(noise_test.NoiseSigma_mps);

noise_base = [ ...
    noise_test.GlobalRMSE_mean_mps(idx_noise_base), ...
    noise_test.CNR_mean(idx_noise_base), ...
    noise_test.DirectKDE_gCNR_mean(idx_noise_base), ...
    noise_test.ContrastRecovery_mean(idx_noise_base)];

noise_stress = [ ...
    noise_test.GlobalRMSE_mean_mps(idx_noise_stress), ...
    noise_test.CNR_mean(idx_noise_stress), ...
    noise_test.DirectKDE_gCNR_mean(idx_noise_stress), ...
    noise_test.ContrastRecovery_mean(idx_noise_stress)];

noise_response = ...
    noise_stress ./ noise_base;

%% Spatial blur

idx_blur_base = ...
    find(abs(blur_test.BlurSigma_mm) < 1e-12, 1);

[~, idx_blur_stress] = ...
    max(blur_test.BlurSigma_mm);

blur_base = [ ...
    blur_test.GlobalRMSE_mps(idx_blur_base), ...
    blur_test.CNR(idx_blur_base), ...
    blur_test.DirectKDE_gCNR(idx_blur_base), ...
    blur_test.ContrastRecovery(idx_blur_base)];

blur_stress = [ ...
    blur_test.GlobalRMSE_mps(idx_blur_stress), ...
    blur_test.CNR(idx_blur_stress), ...
    blur_test.DirectKDE_gCNR(idx_blur_stress), ...
    blur_test.ContrastRecovery(idx_blur_stress)];

blur_response = ...
    blur_stress ./ blur_base;

stress_response = [ ...
    bias_response; ...
    noise_response; ...
    blur_response];

%% ========================================================================
% Prepare sharpness comparison
% ========================================================================

dong_blur_normalized = ...
    blur_test.EdgeSharpness_mps_per_mm ./ ...
    blur_test.EdgeSharpness_mps_per_mm(1);

gt_blur_normalized = ...
    blur_test.GTBoundarySharpness_mps_per_mm ./ ...
    blur_test.GTBoundarySharpness_mps_per_mm(1);

% Noise sensitivity at strongest tested noise level
noise_sigma_max = ...
    sharp_noise.NoiseSigma_mps(end);

dong_noise_max = ...
    sharp_noise.DongSharpness_normalized(end);

gt_noise_max = ...
    sharp_noise.GTBoundarySharpness_normalized(end);

%% ========================================================================
% Create meeting summary figure
% ========================================================================

figure( ...
    'Position', ...
    [100 100 1500 950]);

tiledlayout( ...
    2, ...
    2, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

%% ========================================================================
% PANEL A
% Quantitative reconstruction
% ========================================================================

nexttile;

plot( ...
    GT_SWS, ...
    estimated_SWS, ...
    '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

hold on;

plot( ...
    [min(GT_SWS) max(GT_SWS)], ...
    [min(GT_SWS) max(GT_SWS)], ...
    '--', ...
    'LineWidth', 1.5);

hold off;

grid on;
box on;

xlabel('Ground-truth inclusion SWS [m/s]');
ylabel('Estimated inclusion SWS [m/s]');

title('A. Quantitative SWS reconstruction');

legend( ...
    'Phase-gradient estimate', ...
    'Ideal reconstruction', ...
    'Location', 'northwest');

for k = 1:numel(case_names)

    text( ...
        GT_SWS(k), ...
        estimated_SWS(k), ...
        ['  ' char(case_names(k))], ...
        'VerticalAlignment', 'bottom');

end

%% ========================================================================
% PANEL B
% Detectability
% ========================================================================

nexttile;

yyaxis left

plot( ...
    GT_contrast, ...
    CNR_contrast, ...
    '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

ylabel('CNR');

ylim([0 1.9]);

yyaxis right

plot( ...
    GT_contrast, ...
    gCNR_contrast, ...
    '-s', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

ylabel('Direct-KDE gCNR');

ylim([0 1]);

grid on;
box on;

xlabel('Ground-truth SWS contrast [m/s]');

title('B. Detectability versus stiffness contrast');

legend( ...
    'CNR', ...
    'Direct-KDE gCNR', ...
    'Location', 'best');

%% ========================================================================
% PANEL C
% Metric specificity
% ========================================================================

nexttile;

metric_labels = categorical( ...
    { ...
        'RMSE', ...
        'CNR', ...
        'gCNR', ...
        'Contrast recovery'});

metric_labels = ...
    reordercats( ...
        metric_labels, ...
        { ...
            'RMSE', ...
            'CNR', ...
            'gCNR', ...
            'Contrast recovery'});

bar( ...
    metric_labels, ...
    stress_response.');

hold on;

yline( ...
    1, ...
    '--', ...
    'No change');

hold off;

grid on;
box on;

ylabel('Metric / undegraded baseline');

title('C. Metric specificity under controlled degradation');

legend( ...
    sprintf('Global bias +%.2f m/s', ...
        bias_test.AppliedBias_mps(idx_bias_stress)), ...
    sprintf('Noise SD %.2f m/s', ...
        noise_test.NoiseSigma_mps(idx_noise_stress)), ...
    sprintf('Blur \\sigma %.1f mm', ...
        blur_test.BlurSigma_mm(idx_blur_stress)), ...
    'Location', 'best');

%% ========================================================================
% PANEL D
% Sharpness-metric evaluation
% ========================================================================

nexttile;

plot( ...
    blur_test.BlurSigma_mm, ...
    dong_blur_normalized, ...
    '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

hold on;

plot( ...
    blur_test.BlurSigma_mm, ...
    gt_blur_normalized, ...
    '-s', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

hold off;

grid on;
box on;

xlabel('Gaussian blur \sigma [mm]');
ylabel('Normalized sharpness');

title('D. Spatial sharpness metric response');

legend( ...
    'Dong edge sharpness', ...
    'GT-referenced boundary sharpness', ...
    'Location', 'northeast');

%% Noise-sensitivity annotation

y_max = ...
    max([ ...
        dong_blur_normalized(:); ...
        gt_blur_normalized(:)]);

text( ...
    1.45, ...
    0.72 * y_max, ...
    { ...
        'GT-referenced candidate:', ...
        'monotonic under blur', ...
        sprintf('but noise-sensitive at SD %.2f m/s:', ...
            noise_sigma_max), ...
        sprintf('Dong = %.1fx, GT-ref = %.1fx', ...
            dong_noise_max, ...
            gt_noise_max)}, ...
    'BackgroundColor', 'w', ...
    'EdgeColor', [0.5 0.5 0.5], ...
    'Margin', 6);

%% ========================================================================
% Overall title
% ========================================================================

sgtitle( ...
    'Quality-metric evaluation in synthetic THE phantoms', ...
    'FontWeight', 'bold');

%% ========================================================================
% Save figure
% ========================================================================

png_file = fullfile( ...
    output_dir, ...
    'meeting_quality_metric_summary.png');

pdf_file = fullfile( ...
    output_dir, ...
    'meeting_quality_metric_summary.pdf');

fig_file = fullfile( ...
    output_dir, ...
    'meeting_quality_metric_summary.fig');

exportgraphics( ...
    gcf, ...
    png_file, ...
    'Resolution', 300);

exportgraphics( ...
    gcf, ...
    pdf_file, ...
    'ContentType', 'vector');

savefig( ...
    gcf, ...
    fig_file);

%% ========================================================================
% Create compact meeting table
% ========================================================================

meeting_table = table( ...
    case_names, ...
    GT_SWS, ...
    estimated_SWS, ...
    contrast.InclusionRelativeBias_percent, ...
    CNR_contrast, ...
    gCNR_contrast, ...
    contrast.ContrastRecovery, ...
    'VariableNames', { ...
        'Case', ...
        'GT_Inclusion_SWS_mps', ...
        'Estimated_Inclusion_SWS_mps', ...
        'RelativeBias_percent', ...
        'CNR', ...
        'DirectKDE_gCNR', ...
        'ContrastRecovery'});

writetable( ...
    meeting_table, ...
    fullfile( ...
        output_dir, ...
        'meeting_contrast_summary.csv'));

%% ========================================================================
% Command-window talking points
% ========================================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('MEETING RESULTS SUMMARY\n');
fprintf('============================================================\n');

fprintf('\n1. CONTRAST SWEEP\n');
fprintf('------------------------------------------------------------\n');

for k = 1:height(contrast)

    fprintf( ...
        ['%s: GT %.2f -> estimated %.2f m/s, bias %.1f%%, ' ...
         'CNR %.3f, gCNR %.3f, CR %.3f\n'], ...
        char(case_names(k)), ...
        GT_SWS(k), ...
        estimated_SWS(k), ...
        contrast.InclusionRelativeBias_percent(k), ...
        CNR_contrast(k), ...
        gCNR_contrast(k), ...
        contrast.ContrastRecovery(k));

end

fprintf('\n2. GLOBAL BIAS TEST\n');
fprintf('------------------------------------------------------------\n');

fprintf( ...
    ['Global additive bias changes RMSE/bias, while CNR, gCNR ' ...
     'and contrast recovery remain approximately invariant.\n']);

fprintf('\n3. NOISE TEST\n');
fprintf('------------------------------------------------------------\n');

fprintf( ...
    'At noise SD %.2f m/s: CNR %.3f -> %.3f, gCNR %.3f -> %.3f.\n', ...
    noise_test.NoiseSigma_mps(idx_noise_stress), ...
    noise_test.CNR_mean(idx_noise_base), ...
    noise_test.CNR_mean(idx_noise_stress), ...
    noise_test.DirectKDE_gCNR_mean(idx_noise_base), ...
    noise_test.DirectKDE_gCNR_mean(idx_noise_stress));

fprintf('\n4. BLUR / SHARPNESS TEST\n');
fprintf('------------------------------------------------------------\n');

fprintf( ...
    ['Dong edge sharpness is non-monotonic because the detected ' ...
     'edge set changes strongly under blur.\n']);

fprintf( ...
    ['GT-referenced boundary sharpness decreases monotonically ' ...
     'with blur, but is highly noise-sensitive.\n']);

fprintf('\nSaved meeting summary to:\n');
fprintf('%s\n', output_dir);

fprintf('============================================================\n');