    blur_bkg_relative_bias, ...
    blur_CNR, ...
    blur_gCNR, ...
    blur_contrast_recovery, ...
    blur_edge_accuracy, ...
    blur_edge_sharpness, ...
    blur_gt_boundary_sharpness, ...
    blur_edge_pixels, ...
    'VariableNames', { ...
        'BlurSigma_mm', ...
        'GlobalRMSE_mps', ...
        'InclusionRelativeBias_percent', ...
        'BackgroundRelativeBias_percent', ...
        'CNR', ...
        'DirectKDE_gCNR', ...
        'ContrastRecovery', ...
        'EdgeAccuracy_mm', ...
