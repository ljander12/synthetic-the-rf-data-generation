%% ========================================================================
% Local function: stress-test metrics
% ========================================================================

function metrics = compute_stress_metrics(sws, sws_gt, roi)

valid_speed = ...
    isfinite(sws) & ...
    isfinite(sws_gt) & ...
    sws > 0 & ...
    sws < 10;

incl_mask = ...
    valid_speed & roi.inclusion_core;

bkg_mask = ...
    valid_speed & roi.background_core;

global_mask = ...
    valid_speed & roi.image_mask;

metrics = struct();

metrics.inclusion = ...
    region_metrics_stress( ...
        sws, ...
        sws_gt, ...
        incl_mask);

metrics.background = ...
    region_metrics_stress( ...
        sws, ...
        sws_gt, ...
        bkg_mask);

metrics.global = ...
    region_metrics_stress( ...
        sws, ...
        sws_gt, ...
        global_mask);

%% CNR

mu_i = metrics.inclusion.mean;
mu_b = metrics.background.mean;

sd_i = metrics.inclusion.std;
sd_b = metrics.background.std;

denom = ...
    sqrt(sd_i^2 + sd_b^2);

if isfinite(mu_i) && ...
        isfinite(mu_b) && ...
        denom > 0

    metrics.CNR = ...
        abs(mu_i - mu_b) / denom;

else

    metrics.CNR = NaN;

end

%% Contrast recovery

gt_i = ...
    metrics.inclusion.gt_mean;

gt_b = ...
    metrics.background.gt_mean;

true_contrast = ...
    gt_i - gt_b;

estimated_contrast = ...
    mu_i - mu_b;

metrics.true_contrast_mps = ...
    true_contrast;

metrics.estimated_contrast_mps = ...
    estimated_contrast;

if isfinite(true_contrast) && ...
        abs(true_contrast) > eps

    metrics.contrast_recovery = ...
        estimated_contrast / true_contrast;

else

    metrics.contrast_recovery = NaN;

end

%% Direct-KDE gCNR

pixels_i = ...
    double(sws(incl_mask));

pixels_b = ...
    double(sws(bkg_mask));

if ~isempty(pixels_i) && ...
        ~isempty(pixels_b)

    x_min = ...
        min([pixels_i; pixels_b]);

    x_max = ...
        max([pixels_i; pixels_b]);

    if x_max > x_min

        x_eval = ...
            linspace( ...
                x_min, ...
                x_max, ...
                1000);

        f_i = ...
            ksdensity( ...
                pixels_i, ...
                x_eval);

        f_b = ...
            ksdensity( ...
                pixels_b, ...
                x_eval);

        f_i = ...
            f_i ./ ...
            trapz(x_eval, f_i);

        f_b = ...
            f_b ./ ...
            trapz(x_eval, f_b);

        overlap = ...
            trapz( ...
                x_eval, ...
                min(f_i, f_b));

        metrics.gCNR_directKDE = ...
            1 - overlap;

    else

        metrics.gCNR_directKDE = 0;

    end

else

    metrics.gCNR_directKDE = NaN;

end

end

%% ========================================================================
% Local function: regional metrics
% ========================================================================

function m = region_metrics_stress(sws, gt, mask)

v = double(sws(mask));
g = double(gt(mask));

valid = ...
    isfinite(v) & ...
    isfinite(g);

v = v(valid);
g = g(valid);

m = struct();

if isempty(v)

    m.N = 0;

    m.mean = NaN;
    m.median = NaN;
    m.std = NaN;

    m.gt_mean = NaN;

    m.bias = NaN;
    m.relative_bias_percent = NaN;

    m.MAE = NaN;
    m.RMSE = NaN;

    return;

end

e = ...
    v - g;

m.N = ...
    numel(v);

m.mean = ...
    mean(v);

m.median = ...
    median(v);

m.std = ...
    std(v);

m.gt_mean = ...
    mean(g);

m.bias = ...
    mean(e);

m.MAE = ...
    mean(abs(e));

m.RMSE = ...
    sqrt(mean(e.^2));

if abs(m.gt_mean) > eps

    m.relative_bias_percent = ...
        100 * m.bias / m.gt_mean;

else

    m.relative_bias_percent = NaN;

end

end

%% ========================================================================
% Local function: physically scaled Gaussian blur
% ========================================================================

function sws_blurred = apply_physical_gaussian_blur( ...
    sws, ...
    sigma_m, ...
    dx, ...
    dz)

if sigma_m <= 0

    sws_blurred = sws;
    return;

end

invalid = ...
    ~isfinite(sws);

temp = ...
    double(sws);

% Fill invalid pixels before filtering to avoid NaN propagation.
temp(invalid) = NaN;

temp = ...
    fillmissing( ...
        temp, ...
        'nearest', ...
        1);

temp = ...
    fillmissing( ...
        temp, ...
        'nearest', ...
        2);

%% Convert physical sigma to pixel sigma

sigma_x_px = ...
    sigma_m / dx;

sigma_z_px = ...
    sigma_m / dz;

%% Gaussian kernel in x

half_x = ...
    max(1, ceil(4 * sigma_x_px));

x = ...
    -half_x:half_x;

kernel_x = ...
    exp( ...
        -0.5 * ...
        (x ./ sigma_x_px).^2);

kernel_x = ...
    kernel_x ./ sum(kernel_x);

%% Gaussian kernel in z

half_z = ...
    max(1, ceil(4 * sigma_z_px));

z = ...
    -half_z:half_z;

kernel_z = ...
    exp( ...
        -0.5 * ...
        (z ./ sigma_z_px).^2);

kernel_z = ...
    kernel_z ./ sum(kernel_z);

%% Separable 2-D convolution

sws_blurred = ...
    conv2( ...
        kernel_z(:), ...
        kernel_x(:).', ...
        temp, ...
        'same');

% Restore originally invalid pixels.
sws_blurred(invalid) = NaN;

end

%% ========================================================================
% Local function: Dong-style edge metrics for stress test
% ========================================================================

function em = compute_edge_metrics_stress( ...
    sws, ...
    sws_gt, ...
    x_axis, ...
    z_axis, ...
    c_bkg, ...
    c_incl)

em = struct();

em.edge_accuracy_mm = NaN;
em.edge_sharpness_mps_per_mm = NaN;
em.detected_edge_pixels = 0;

%% Native spacing

dx = ...
    median(abs(diff(x_axis)));

dz = ...
    median(abs(diff(z_axis)));

r0 = ...
    min(dx, dz);

%% Isotropic evaluation grid

x_iso = ...
    (min(x_axis):r0:max(x_axis)).';

z_iso = ...
    (min(z_axis):r0:max(z_axis)).';

[X_iso, Z_iso] = ...
    meshgrid( ...
        x_iso, ...
        z_iso);

%% Estimated SWS

sws_iso = ...
    interp2( ...
        x_axis, ...
        z_axis, ...
        double(sws), ...
        X_iso, ...
        Z_iso, ...
        'linear', ...
        NaN);

%% Ground truth

gt_iso = ...
    interp2( ...
        x_axis, ...
        z_axis, ...
        double(sws_gt), ...
        X_iso, ...
        Z_iso, ...
        'nearest', ...
        NaN);

%% GT inclusion mask

midpoint = ...
    0.5 * ...
    (double(c_bkg) + double(c_incl));

if c_incl > c_bkg

    gt_inclusion = ...
        isfinite(gt_iso) & ...
        gt_iso > midpoint;

else

    gt_inclusion = ...
        isfinite(gt_iso) & ...
        gt_iso < midpoint;

end

if ~any(gt_inclusion(:))
    return;
end

gt_edge = ...
    bwperim( ...
        gt_inclusion, ...
        8);

%% Prepare estimated SWS for edge detection

sws_edge_input = ...
    sws_iso;

invalid = ...
    ~isfinite(sws_edge_input) | ...
    sws_edge_input <= 0 | ...
    sws_edge_input >= 10;

sws_edge_input(invalid) = NaN;

sws_edge_input = ...
    fillmissing( ...
        sws_edge_input, ...
        'nearest', ...
        1);

sws_edge_input = ...
    fillmissing( ...
        sws_edge_input, ...
        'nearest', ...
        2);

sws_edge_input( ...
    ~isfinite(sws_edge_input)) = ...
    double(c_bkg);

%% Normalize before edge()

valid_values = ...
    sws_edge_input( ...
        isfinite(sws_edge_input));

if isempty(valid_values)
    return;
end

sws_min = ...
    min(valid_values);

sws_max = ...
    max(valid_values);

if sws_max <= sws_min
    return;
end

sws_norm = ...
    (sws_edge_input - sws_min) ./ ...
    (sws_max - sws_min);

sws_norm = ...
    max( ...
        0, ...
        min( ...
            1, ...
            sws_norm));

%% MATLAB default edge detector

estimated_edge_all = ...
    edge(sws_norm);

%% Same GT-based search region used in main analysis

[gt_rows, gt_cols] = ...
    find(gt_inclusion);

row_min = ...
    min(gt_rows);

row_max = ...
    max(gt_rows);

col_min = ...
    min(gt_cols);

col_max = ...
    max(gt_cols);

height_px = ...
    row_max - row_min + 1;

width_px = ...
    col_max - col_min + 1;

margin_px = ...
    max( ...
        3, ...
        round( ...
            0.5 * ...
            max( ...
                height_px, ...
                width_px)));

row1 = ...
    max( ...
        1, ...
        row_min - margin_px);

row2 = ...
    min( ...
        size(gt_inclusion,1), ...
        row_max + margin_px);

col1 = ...
    max( ...
        1, ...
        col_min - margin_px);

col2 = ...
    min( ...
        size(gt_inclusion,2), ...
        col_max + margin_px);

search_mask = ...
    false(size(gt_inclusion));

search_mask( ...
    row1:row2, ...
    col1:col2) = true;

estimated_edge = ...
    estimated_edge_all & ...
    search_mask;

N_edge = ...
    nnz(estimated_edge);

em.detected_edge_pixels = ...
    N_edge;

if N_edge == 0
    return;
end

%% Edge accuracy

distance_to_gt = ...
    bwdist(gt_edge);

em.edge_accuracy_mm = ...
    mean( ...
        distance_to_gt(estimated_edge), ...
        'omitnan') * ...
    r0 * ...
    1e3;

%% Edge sharpness

[dSWS_dx_pixel, dSWS_dz_pixel] = ...
    gradient(sws_edge_input);

grad_mag_pixel = ...
    sqrt( ...
        dSWS_dx_pixel.^2 + ...
        dSWS_dz_pixel.^2);

sharpness_pixel = ...
    mean( ...
        grad_mag_pixel(estimated_edge), ...
        'omitnan');

em.edge_sharpness_mps_per_mm = ...
    sharpness_pixel / ...
    (r0 * 1e3);

end

%% ========================================================================
% Local function: GT-referenced boundary sharpness
% ========================================================================

function out = compute_gt_boundary_sharpness( ...
    sws, ...
    sws_gt, ...
    x_axis, ...
    z_axis, ...
    c_bkg, ...
    c_incl)

out = struct();

out.mean_gradient_mps_per_mm = NaN;
out.boundary_pixels = 0;

%% Native spacing

dx = ...
    median(abs(diff(x_axis)));

dz = ...
    median(abs(diff(z_axis)));

% Use same isotropic evaluation spacing as Dong-style metrics
r0 = ...
    min(dx, dz);

r0_mm = ...
    r0 * 1e3;

%% Isotropic grid

x_iso = ...
    (min(x_axis):r0:max(x_axis)).';

z_iso = ...
    (min(z_axis):r0:max(z_axis)).';

[X_iso, Z_iso] = ...
    meshgrid( ...
        x_iso, ...
        z_iso);

%% Resample estimated SWS

sws_iso = ...
    interp2( ...
        x_axis, ...
        z_axis, ...
        double(sws), ...
        X_iso, ...
        Z_iso, ...
        'linear', ...
        NaN);

%% Resample GT using nearest neighbour

gt_iso = ...
    interp2( ...
        x_axis, ...
        z_axis, ...
        double(sws_gt), ...
        X_iso, ...
        Z_iso, ...
        'nearest', ...
        NaN);

%% Build exact GT inclusion mask

midpoint = ...
    0.5 * ...
    (double(c_bkg) + double(c_incl));

if c_incl > c_bkg

    gt_inclusion = ...
        isfinite(gt_iso) & ...
        gt_iso > midpoint;

else

    gt_inclusion = ...
        isfinite(gt_iso) & ...
        gt_iso < midpoint;

end

if ~any(gt_inclusion(:))
    return;
end

%% Fixed GT boundary

gt_edge = ...
    bwperim( ...
        gt_inclusion, ...
        8);

out.boundary_pixels = ...
    nnz(gt_edge);

if out.boundary_pixels == 0
    return;
end

%% Prepare SWS map for gradient calculation

sws_grad = ...
    sws_iso;

sws_grad( ...
    ~isfinite(sws_grad)) = NaN;

sws_grad = ...
    fillmissing( ...
        sws_grad, ...
        'nearest', ...
        1);

sws_grad = ...
    fillmissing( ...
        sws_grad, ...
        'nearest', ...
        2);

if any(~isfinite(sws_grad(:)))
    return;
end

%% Physical spatial gradient
% r0_mm gives gradient directly in m/s/mm.

[dSWS_dx, dSWS_dz] = ...
    gradient( ...
        sws_grad, ...
        r0_mm, ...
        r0_mm);

gradient_magnitude = ...
    sqrt( ...
        dSWS_dx.^2 + ...
        dSWS_dz.^2);

%% Sharpness evaluated at the SAME GT boundary for every test case

boundary_values = ...
    gradient_magnitude(gt_edge);

boundary_values = ...
    boundary_values( ...
        isfinite(boundary_values));

if isempty(boundary_values)
    return;
end

out.mean_gradient_mps_per_mm = ...
    mean(boundary_values);

end