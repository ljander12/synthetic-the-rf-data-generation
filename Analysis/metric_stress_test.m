%% ========================================================================
% STRESS TEST 3
% Controlled spatial Gaussian blur
%
% High-contrast case is used because it has a detectable inclusion edge
% in the undegraded reconstruction.
% ========================================================================

fprintf('\n');
fprintf('============================================\n');
fprintf('SPATIAL GAUSSIAN BLUR STRESS TEST\n');
fprintf('============================================\n');

%% Load high-contrast reconstruction

blur_result_file = fullfile( ...
    repo_dir, ...
    'Results', ...
    'high_contrast', ...
    'high_contrast_SWS_quality_results.mat');

S_blur = load(blur_result_file);

if ~isfield(S_blur.results, 'roi')
    error(['High-contrast results do not contain ROI masks. ' ...
        'Re-run high_contrast analysis first.']);
end

if ~isfield(S_blur.results, 'x_axis') || ...
        ~isfield(S_blur.results, 'z_axis')

    error(['High-contrast results do not contain x_axis/z_axis. ' ...
        'Re-run high_contrast analysis after storing the axes.']);
end

sws_blur_base = ...
    double(S_blur.sws_map);

sws_gt_blur = ...
    double(S_blur.sws_gt);

roi_blur = ...
    S_blur.results.roi;

x_blur = ...
    double(S_blur.results.x_axis(:));

z_blur = ...
    double(S_blur.results.z_axis(:));

dx_blur = ...
    median(abs(diff(x_blur)));

dz_blur = ...
    median(abs(diff(z_blur)));

%% Ground-truth material speeds

c_incl_blur = ...
    median( ...
        sws_gt_blur(roi_blur.inclusion_core), ...
        'omitnan');

c_bkg_blur = ...
    median( ...
        sws_gt_blur(roi_blur.background_core), ...
        'omitnan');

%% Blur levels
% Gaussian sigma in physical space.

blur_sigma_mm = [ ...
    0.0, ...
    0.5, ...
    1.0, ...
    2.0, ...
    3.0];

N_blur = ...
    numel(blur_sigma_mm);

%% Allocate

blur_global_rmse = ...
    nan(N_blur,1);

blur_CNR = ...
    nan(N_blur,1);

blur_gCNR = ...
    nan(N_blur,1);

blur_contrast_recovery = ...
    nan(N_blur,1);

blur_incl_relative_bias = ...
    nan(N_blur,1);

blur_bkg_relative_bias = ...
    nan(N_blur,1);

blur_edge_accuracy = nan(N_blur,1);
blur_edge_sharpness = nan(N_blur,1);
blur_edge_pixels = zeros(N_blur,1);

% Candidate metric:
% sharpness evaluated at the fixed ground-truth boundary
blur_gt_boundary_sharpness = nan(N_blur,1);

%% ========================================================================
% Run blur test
% ========================================================================

for k = 1:N_blur
    %% GT-referenced boundary sharpness

    sigma_mm = ...
        blur_sigma_mm(k);

    sigma_m = ...
        sigma_mm * 1e-3;

    fprintf( ...
        'Blur sigma %.2f mm\n', ...
        sigma_mm);

    %% Apply physically scaled Gaussian blur

    sws_test = ...
        apply_physical_gaussian_blur( ...
            sws_blur_base, ...
            sigma_m, ...
            dx_blur, ...
            dz_blur);

    %% Regional / global metrics

    m = ...
        compute_stress_metrics( ...
            sws_test, ...
            sws_gt_blur, ...
            roi_blur);

    blur_global_rmse(k) = ...
        m.global.RMSE;

    blur_CNR(k) = ...
        m.CNR;

    blur_gCNR(k) = ...
        m.gCNR_directKDE;

    blur_contrast_recovery(k) = ...
        m.contrast_recovery;

    blur_incl_relative_bias(k) = ...
        m.inclusion.relative_bias_percent;

    blur_bkg_relative_bias(k) = ...
        m.background.relative_bias_percent;

    %% Dong-style edge metrics

    em = ...
        compute_edge_metrics_stress( ...
            sws_test, ...
            sws_gt_blur, ...
            x_blur, ...
            z_blur, ...
            c_bkg_blur, ...
            c_incl_blur);

    blur_edge_accuracy(k) = ...
        em.edge_accuracy_mm;

    blur_edge_sharpness(k) = ...
        em.edge_sharpness_mps_per_mm;

    blur_edge_pixels(k) = ...
        em.detected_edge_pixels;
    %% GT-referenced boundary sharpness

gt_sharp = ...
    compute_gt_boundary_sharpness( ...
        sws_test, ...
        sws_gt_blur, ...
        x_blur, ...
        z_blur, ...
        c_bkg_blur, ...
        c_incl_blur);

blur_gt_boundary_sharpness(k) = ...
    gt_sharp.mean_gradient_mps_per_mm;

end

%% ========================================================================
% Result table
% ========================================================================

