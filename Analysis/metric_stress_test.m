    isfinite(sws_baseline);

%% Run repeated noise test

for k = 1:N_noise

    sigma_noise = ...
        noise_sigma(k);

    fprintf( ...
        'Noise sigma %.3f m/s\n', ...
        sigma_noise);

    for r = 1:N_realizations

        % Reproducible random realization
        rng(30000 + 100*k + r, 'twister');

        sws_test = ...
            sws_baseline;

        noise_here = ...
            sigma_noise .* ...
            randn(nnz(valid_baseline), 1);

        sws_test(valid_baseline) = ...
            sws_baseline(valid_baseline) + ...
            noise_here;

        %% Compute metrics

        m = compute_stress_metrics( ...
            sws_test, ...
            sws_gt, ...
            roi);

        noise_global_bias(k,r) = ...
            m.global.bias;

        noise_global_rmse(k,r) = ...
            m.global.RMSE;

        noise_incl_bias(k,r) = ...
            m.inclusion.bias;

        noise_incl_relative_bias(k,r) = ...
            m.inclusion.relative_bias_percent;

        noise_incl_sd(k,r) = ...
            m.inclusion.std;

        noise_bkg_bias(k,r) = ...
            m.background.bias;

        noise_bkg_relative_bias(k,r) = ...
            m.background.relative_bias_percent;

        noise_bkg_sd(k,r) = ...
            m.background.std;

        noise_CNR(k,r) = ...
            m.CNR;

        noise_gCNR(k,r) = ...
            m.gCNR_directKDE;

        noise_contrast_recovery(k,r) = ...
            m.contrast_recovery;

    end

end

