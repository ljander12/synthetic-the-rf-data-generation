%% Metric stress test
% Controlled degradation of an existing reconstructed SWS map.
%
% Test 1:
%   Global additive SWS bias
%
% Purpose:
%   Evaluate which quality metrics respond to absolute quantitative bias,
%   and which remain insensitive to a common shift of the SWS map.

clear;
clc;
close all;

%% ========================================================================
% Paths
% ========================================================================

analysis_dir = fileparts(mfilename('fullpath'));
repo_dir = fileparts(analysis_dir);

result_file = fullfile( ...
    repo_dir, ...
    'Results', ...
    'chaoran_baseline', ...
    'chaoran_baseline_SWS_quality_results.mat');

output_dir = fullfile( ...
    repo_dir, ...
    'Results', ...
    'metric_stress_test');

if ~isfolder(output_dir)
    mkdir(output_dir);
end

%% ========================================================================
% Load baseline reconstruction
% ========================================================================

S = load(result_file);

if ~isfield(S, 'sws_map') || ...
        ~isfield(S, 'sws_gt') || ...
        ~isfield(S, 'results')

    error('Required SWS results are missing.');

end

if ~isfield(S.results, 'roi')
    error('Saved results do not contain ROI masks.');
end

sws_baseline = double(S.sws_map);
sws_gt = double(S.sws_gt);
roi = S.results.roi;

%% ========================================================================
% Controlled global bias levels
% ========================================================================

bias_levels = [ ...
    -0.50, ...
    -0.25, ...
     0.00, ...
     0.25, ...
     0.50];

N = numel(bias_levels);

%% ========================================================================
% Allocate results
% ========================================================================

global_bias = nan(N,1);
global_rmse = nan(N,1);

incl_bias = nan(N,1);
incl_relative_bias = nan(N,1);

bkg_bias = nan(N,1);
bkg_relative_bias = nan(N,1);

CNR = nan(N,1);
gCNR = nan(N,1);

contrast_recovery = nan(N,1);

%% ========================================================================
% Run stress test
% ========================================================================

for k = 1:N

    delta = bias_levels(k);

    sws_test = ...
        sws_baseline + delta;

    m = compute_stress_metrics( ...
        sws_test, ...
        sws_gt, ...
        roi);

    global_bias(k) = ...
        m.global.bias;

    global_rmse(k) = ...
        m.global.RMSE;

    incl_bias(k) = ...
        m.inclusion.bias;

    incl_relative_bias(k) = ...
        m.inclusion.relative_bias_percent;

    bkg_bias(k) = ...
        m.background.bias;

    bkg_relative_bias(k) = ...
        m.background.relative_bias_percent;

    CNR(k) = ...
        m.CNR;

    gCNR(k) = ...
        m.gCNR_directKDE;

    contrast_recovery(k) = ...
        m.contrast_recovery;

end

%% ========================================================================
% Result table
% ========================================================================

stress_table = table( ...
    bias_levels(:), ...
    global_bias, ...
    global_rmse, ...
    incl_bias, ...
    incl_relative_bias, ...
    bkg_bias, ...
    bkg_relative_bias, ...
    CNR, ...
    gCNR, ...
    contrast_recovery, ...
    'VariableNames', { ...
        'AppliedBias_mps', ...
        'GlobalBias_mps', ...
        'GlobalRMSE_mps', ...
        'InclusionBias_mps', ...
        'InclusionRelativeBias_percent', ...
        'BackgroundBias_mps', ...
        'BackgroundRelativeBias_percent', ...
        'CNR', ...
        'DirectKDE_gCNR', ...
        'ContrastRecovery'});

disp(stress_table);

writetable( ...
    stress_table, ...
    fullfile( ...
        output_dir, ...
        'global_bias_stress_test.csv'));

