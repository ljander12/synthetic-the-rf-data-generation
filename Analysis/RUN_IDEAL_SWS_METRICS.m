%% RUN_IDEAL_SWS_METRICS.m
% ONE-CLICK evaluation of the eight geometrically exact SWS phantoms made by
% RUN_IDEAL_SWS_PHANTOMS.m. No k-Wave, Field II, USTB, or RF processing.
%
% Output: reference SWS, Correlation Q, RMI-1D, error / masked-stiffness
% figures, and a CSV with RMSE, bias, CNR, gCNR, contrast recovery,
% edge accuracy, edge sharpness, AUC and false confidence where defined.
%
% IMPORTANT SCIENTIFIC LIMITATIONS:
%   (1) Ideal SWS ground truth ALONE cannot produce correlation Q or RMI.
%       We generate an ANALYTIC, kinematic traveling displacement wave
%       using the known reference speed as a prescribed delay field.
%       This does NOT model elastic scattering/reflections at inclusions.
%   (2) Correlation Q is the project's ZERO-LAG adapted implementation of
%       the Schoen et al. (2025) score mapping, not an exact reproduction.
%   (3) RMI-1D uses Choi et al. (2015) Eq. 6 and the project's 80/20
%       normalization. Normalization limits below are calibrated only
%       on these synthetic waveforms, not the production phantom data.
%   (4) Perfect SWS has no wrong pixels: AUC/false-confidence detection
%       cannot be assessed in the ideal-only cases (AUC = NaN).
%   (5) The optional local bias is imposed ONLY on the estimated SWS;
%       the analytic displacement field is unchanged by design.
%       Therefore correlation Q must NOT respond to that bias.
%
% Only TWO GT-independent quality metrics: Correlation Q and RMI-1D.
% No Phase Planarity Q or Log-RMI.

clear; clc; close all;
rng(42,'twister');

%% USER SETTINGS
RUN_LOCAL_BIAS_CONTROL = true;      % also test +1.0 m/s in a small patch
SHOW_SUMMARY_FIGURES  = true;      % show overview quality maps
SAVE_INDIVIDUAL_FIGURES = true;
frequency_Hz = 200;
PRF_Hz = 3000;
Nt = 60;
rho_kg_m3 = 1000;
wrong_speed_limit_mps = 0.5;
correlation_threshold = 0.63;      % illustrative, not universal
rmi_threshold = 0.85;              % illustrative, not universal

%% FILES: read SAME *_GT.mat generated by RUN_IDEAL_SWS_PHANTOMS
here = fileparts(mfilename('fullpath'));
if isfolder(fullfile(here,'Results'))
    repo = here;
else
    repo = fileparts(here);
end
input_dir = fullfile(repo,'Results','artificial_sws_validation','ideal_phantoms');
output_dir = fullfile(input_dir,'metric_evaluation');
assert(isfolder(input_dir), ...
    'No ideal phantoms found at %s. Run RUN_IDEAL_SWS_PHANTOMS first.',input_dir);
if ~isfolder(output_dir), mkdir(output_dir); end

case_names = { ...
    'homogeneous','small_inclusion','large_inclusion','high_contrast', ...
    'low_contrast','soft_inclusion','two_inclusions','elliptical_inclusion'};

for k = 1:numel(case_names)
    f = fullfile(input_dir,[case_names{k} '_GT.mat']);
    assert(isfile(f),'Missing ideal phantom: %s',f);
end

%% STEP A: FIXED RMI CALIBRATION, USING SYNTHETIC u ONLY (NOT ERROR LABELS)
% These bounds are frozen across all eight maps and both modes. This is
% NOT the previously published/stored calibration from real displacement.
res_samples = [];
amp_samples = [];
for k = 1:numel(case_names)
    D = load(fullfile(input_dir,[case_names{k} '_GT.mat']), ...
        'sws_gt','x_axis','z_axis');
    gt = double(D.sws_gt);
    x = double(D.x_axis(:).');
    z = double(D.z_axis(:));
    assert(isequal(size(gt),[numel(z) numel(x)]), ...
        'Stored GT does not match x/z axes for %s.',case_names{k});
    u = make_travel_time_wave(gt,x,z,Nt,PRF_Hz,frequency_Hz);
    [res,amp] = wave_residual(u,gt,x,PRF_Hz);
    v1 = res(3:5:end-2,3:5:end-2);
    v2 = amp(3:5:end-2,3:5:end-2);
    res_samples = [res_samples;double(v1(isfinite(v1)))]; %#ok<AGROW>
    amp_samples = [amp_samples;double(v2(isfinite(v2)))]; %#ok<AGROW>
    clear D u res amp;
end
assert(numel(res_samples)>200 && numel(amp_samples)>200, ...
    'Too few synthetic residual samples for calibration.');
cal = struct();
cal.res_min = simple_prctile(res_samples,5);
cal.res_max = simple_prctile(res_samples,95);
cal.u_min = simple_prctile(amp_samples,5);
cal.u_max = simple_prctile(amp_samples,95);
cal.source = 'Eight analytical travel-time wavefields; within-study calibration';
cal.is_production_calibration = false;
assert(cal.res_max > cal.res_min && cal.u_max > cal.u_min, ...
    'RMI calibration bounds collapsed. Inspect analytical displacement.');
save(fullfile(output_dir,'synthetic_RMI_calibration.mat'),'cal');

%% STEP B: COMPUTE GT-BASED AND GT-INDEPENDENT METRICS
T = table();
Q_ideal = cell(1,numel(case_names));
RMI_ideal = cell(1,numel(case_names));
SWS_ideal = cell(1,numel(case_names));

fprintf('\n=== IDEAL SWS PHANTOMS + QUALITY METRICS ===\n');
fprintf('Exact SWS reference; synthetic kinematic u; no elastic wave simulation.\n');
fprintf('Correlation Q: zero-lag adaptation | RMI: 1D Eq.6 adaptation.\n');
fprintf('RMI calibration fixed across the eight synthetic cases.\n\n');

for k = 1:numel(case_names)
    name = case_names{k};
    D = load(fullfile(input_dir,[name '_GT.mat']), ...
        'sws_gt','inclusion_mask','x_axis','z_axis');
    gt = double(D.sws_gt);
    inc = logical(D.inclusion_mask);
    x = double(D.x_axis(:).');
    z = double(D.z_axis(:));
    [X,Z] = meshgrid(x,z);
    u = make_travel_time_wave(gt,x,z,Nt,PRF_Hz,frequency_Hz);
    Q = correlation_q_from_displacement(u);
    
    % Restrict all comparisons to a common, interior evaluation region.
    eval_mask = X >= min(x)+0.003 & X <= max(x)-0.003 & ...
                Z >= min(z)+0.003 & Z <= max(z)-0.003;

    for variant = 1:(1+double(RUN_LOCAL_BIAS_CONTROL))
        c_est = gt;
        label = 'ideal';
        if variant == 2
            label = 'local_bias';
            patch = X>=0.006 & X<=0.013 & Z>=0.033 & Z<=0.042;
            c_est(patch) = c_est(patch)+1.00; % KNOWN artificial error
        end

        [res,amp] = wave_residual(u,c_est,x,PRF_Hz);
        RMI = rmi_1d(res,amp,cal);
        valid = eval_mask & isfinite(gt) & isfinite(c_est) & ...
                isfinite(Q) & isfinite(RMI);
        assert(nnz(valid)>100, 'No common quality pixels in %s.',name);
        err = abs(c_est-gt);
        bad = err(valid)>wrong_speed_limit_mps;
        cq = Q(valid); ri = RMI(valid);
        stats = evaluate_sws(c_est,gt,inc,valid,x,z);
        
        Q_AUC = calc_auc(cq,~bad);
        RMI_AUC = calc_auc(ri,~bad);
        % False-confidence not meaningful if there are no erroneous pixels.
        Q_FC = NaN; RMI_FC = NaN;
        if any(bad)
            Q_FC = top_half_wrong_fraction(cq,bad);
            RMI_FC = top_half_wrong_fraction(ri,bad);
        end
        Q_coverage = mean(cq>=correlation_threshold);
        RMI_coverage = mean(ri>=rmi_threshold);
        
        row = table(string(name),string(label),nnz(valid), ...
            stats.RMSE,stats.Bias,stats.MAE, ...
            stats.CNR,stats.gCNR_hist,stats.ContrastRecovery_pct, ...
            stats.EdgeAccuracy_mm,stats.EdgeSharpness_mps_per_mm, ...
            NaN, ... % SNR undefined: no injected displacement noise
            mean(cq),mean(ri),Q_AUC,RMI_AUC,Q_FC,RMI_FC, ...
            Q_coverage,RMI_coverage, ...
            'VariableNames',{'Phantom','Variant','N', ...
            'RMSE_mps','Bias_mps','MAE_mps','CNR', ...
            'gCNR_hist_exploratory','ContrastRecovery_percent', ...
            'EdgeAccuracy_mm','EdgeSharpness_mps_per_mm', ...
            'InjectedDisplacementSNR_dB', ...
            'CorrelationQ_mean','RMI1D_mean','CorrelationQ_AUC', ...
            'RMI1D_AUC','CorrelationQ_falseConfidenceTop50', ...
            'RMI1D_falseConfidenceTop50','CorrelationQ_coverage', ...
            'RMI1D_coverage'});
        T = [T;row]; %#ok<AGROW>

        if variant==1
            Q_ideal{k}=Q;
            RMI_ideal{k}=RMI;
            SWS_ideal{k}=gt;
        end
        
        % Save exact maps and quality outputs for later report figures.
        save(fullfile(output_dir,[name '_' label '_metrics.mat']), ...
            'gt','c_est','Q','RMI','res','amp','valid','inc','x','z', ...
            'cal','correlation_threshold','rmi_threshold');
        if SAVE_INDIVIDUAL_FIGURES
            draw_detail(output_dir,name,label,x,z,gt,c_est,err,Q,RMI,valid, ...
                rho_kg_m3,correlation_threshold,rmi_threshold);
        end
        fprintf('%-24s %-11s RMSE=%5.3f | CNR=%7.3g | CR=%7.2f%% | Q=%5.3f | RMI=%5.3f | AUC=[%5.3f, %5.3f]\n', ...
            name,label,stats.RMSE,stats.CNR,stats.ContrastRecovery_pct, ...
            mean(cq),mean(ri),Q_AUC,RMI_AUC);
    end
end

writetable(T,fullfile(output_dir,'all_ideal_phantom_metrics.csv'));
save(fullfile(output_dir,'all_ideal_phantom_metrics.mat'),'T','cal');

draw_overview(output_dir,case_names,x,z,SWS_ideal,'SWS [m/s]', ...
    [1.0 6.2],'ideal_sws_8_maps.png',false);
draw_overview(output_dir,case_names,x,z,Q_ideal,'Correlation Q [0,1]', ...
    [0 1],'correlation_q_8_maps.png',SHOW_SUMMARY_FIGURES);
draw_overview(output_dir,case_names,x,z,RMI_ideal,'RMI-1D [0,1]', ...
    [0 1],'rmi_1d_8_maps.png',SHOW_SUMMARY_FIGURES);

fprintf('\nSaved analysis to:\n%s\n',output_dir);
fprintf(['Ideal maps: RMSE = 0 and AUC = NaN (no incorrect SWS pixels).\n' ...
    'CNR = Inf when the two classes are exactly constant; not a numeric bug.\n' ...
    'SNR = NaN (no displacement noise injected).\n' ...
    'Two-inclusion CR is undefined as one contrast value; reported NaN.\n' ...
    'Local-bias control changes ONLY c_est; correlation Q therefore stays fixed.\n' ...
    'Analytical wavefields are NOT solutions of a heterogeneous elastic PDE.\n' ...
    'Do not interpret Q/RMI as clinical or physically validated on these maps.\n']);

%% ------------------------ LOCAL FUNCTIONS -------------------------------
function u=make_travel_time_wave(c,x,z,Nt,prf,f)
% Kinematic lateral wave: u=A(x,z)*cos(2pi*f*(t-tau(x,z))).
% tau(x,z)=integral_x (1/c(s,z)) ds; no 2-D scattering or reflection.
    [Nz,Nx]=size(c);
    dtau=0.5*(1./c(:,1:end-1)+1./c(:,2:end));
    dtau=bsxfun(@times,dtau,diff(x));
    tau=[zeros(Nz,1),cumsum(dtau,2)];
    [X,Z]=meshgrid(x,z);
    amplitude=(1+0.10*cos(2*pi*(X-min(x))/(max(x)-min(x)))) .* ...
        exp(-0.15*(Z-min(z))/(max(z)-min(z)));
    u=zeros(Nz,Nx,Nt,'single');
    for j=1:Nt
        u(:,:,j)=single(amplitude.*cos(2*pi*f*((j-1)/prf-tau)));
    end
end

function Q=correlation_q_from_displacement(u)
% Matched to the zero-lag adapted quality calculation in project's
% RUN_ARTIFICIAL_SWS_VALIDATION.m. Not full lag-max cross-correlation.
    [Nz,Nx,Nt]=size(u);
    s1=zeros(Nz,Nx-1);s2=s1;s11=s1;s22=s1;s12=s1;
    for it=1:Nt
        a=double(u(:,1:end-1,it));b=double(u(:,2:end,it));
        s1=s1+a;s2=s2+b;s11=s11+a.^2;s22=s22+b.^2;s12=s12+a.*b;
    end
    nom=s12-s1.*s2/Nt;
    va=max(0,s11-s1.^2/Nt);vb=max(0,s22-s2.^2/Nt);
    den=sqrt(va.*vb);
    rho=nom./den;
    rho(den<=eps(max(den(:))))=NaN;
    rho=max(-1,min(1,rho));
    strength=20*log10(max(abs(rho),realmin));
    qpair=nan(size(strength));
    qpair(strength>=-10)=1;
    mid=strength>-50 & strength<-10;
    qpair(mid)=cos((pi/2)*(strength(mid)+10)/40);
    qpair(strength<=-50)=0;
    Q=nan(Nz,Nx);
    Q(:,1)=qpair(:,1);
    Q(:,end)=qpair(:,end);
    Q(:,2:end-1)=min(qpair(:,1:end-1),qpair(:,2:end));
end

function [res,amp]=wave_residual(u,c,x,prf)
% Normalized Eq.6, spatial derivative along lateral x only.
    [Nz,Nx,Nt]=size(u);
    assert(Nx>=5 && Nt>=5,'Insufficient samples for PDE residual.');
    dx0=diff(x);
    assert(all(dx0>0),'x axis must be strictly increasing.');
    den=zeros(Nz,Nx);num=den;
    amp=zeros(Nz,Nx);
    dr=x(3:end)-x(2:end-1);
    dl=x(2:end-1)-x(1:end-2);
    span=x(3:end)-x(1:end-2);
    speed2=c(:,2:end-1).^2;
    for it=2:Nt-1
        u0=double(u(:,:,it));
        up=double(u(:,:,it+1));um=double(u(:,:,it-1));
        utt=(up-2*u0+um)*prf^2;
        forward=bsxfun(@rdivide,u0(:,3:end)-u0(:,2:end-1),dr);
        backward=bsxfun(@rdivide,u0(:,2:end-1)-u0(:,1:end-2),dl);
        uxx=bsxfun(@rdivide,2*(forward-backward),span);
        difference=utt(:,2:end-1)-speed2.*uxx;
        num(:,2:end-1)=num(:,2:end-1)+difference.^2;
        den(:,2:end-1)=den(:,2:end-1)+uxx.^2;
        amp=max(amp,abs(u0));
    end
    amp=max(amp,abs(double(u(:,:,1))));
    amp=max(amp,abs(double(u(:,:,end))));
    good=den(isfinite(den)&den>0);
    assert(~isempty(good),'All spatial curvatures are zero.');
    floor_den=median(good)*1e-12;
    res=num./den;
    res(:,[1,end])=NaN;
    res(~isfinite(den)|den<=floor_den)=NaN;
end

function rmi=rmi_1d(res,amp,cal)
    qr=(cal.res_max-res)/(cal.res_max-cal.res_min);
    qa=(amp-cal.u_min)/(cal.u_max-cal.u_min);
    qr=max(0,min(1,qr));qa=max(0,min(1,qa));
    rmi=0.8*qr+0.2*qa;
    rmi(~isfinite(res)|~isfinite(amp))=NaN;
end

function v=simple_prctile(x,p)
    a=sort(double(x(isfinite(x))));
    assert(numel(a)>1,'Not enough data for percentile.');
    pos=1+(numel(a)-1)*p/100;
    lo=floor(pos);hi=ceil(pos);
    v=a(lo)+(pos-lo)*(a(hi)-a(lo));
end

function S=evaluate_sws(est,gt,inc,valid,x,z)
    difference=double(est(valid)-gt(valid));
    S=struct('RMSE',sqrt(mean(difference.^2)), ...
        'Bias',mean(difference),'MAE',mean(abs(difference)), ...
        'CNR',NaN,'gCNR_hist',NaN,'ContrastRecovery_pct',NaN, ...
        'EdgeAccuracy_mm',NaN,'EdgeSharpness_mps_per_mm',NaN);
    if ~any(inc(:)),return;end
    incl=valid & inc;
    back=valid & ~inc;
    a=double(est(incl));b=double(est(back));
    if isempty(a)||isempty(b),return;end
    c=mean(a)-mean(b);
    sd=sqrt(var(a)+var(b));
    if sd < 1e-10*max(1,abs(c))
        S.CNR=Inf; % exactly uniform SWS in each class
    else
        S.CNR=abs(c)/sd;
    end
    % For mixed stiff + soft inclusions there is NO unique signed contrast.
    incl_speeds=unique(gt(inc));
    if numel(incl_speeds)==1
        true_difference=mean(gt(incl))-mean(gt(back));
        if abs(true_difference)>eps
            S.ContrastRecovery_pct=100*c/true_difference;
        end
    else
        S.CNR=NaN; % one aggregate inclusion/background CNR is misleading
    end
    % Descriptive histogram gCNR (not the project's published tKDE gCNR).
    lo=min([a;b]);hi=max([a;b]);
    if hi>lo
        edges=linspace(lo,hi,101);
        h1=histcounts(a,edges,'Normalization','probability');
        h2=histcounts(b,edges,'Normalization','probability');
        S.gCNR_hist=max(0,min(1,1-sum(min(h1,h2))));
    elseif numel(incl_speeds)==1
        S.gCNR_hist=0;
    end
    % Edge accuracy/sharpness need MATLAB Image Processing Toolbox.
    if exist('edge','file')~=2 || exist('bwperim','file')~=2 || ...
            exist('bwdist','file')~=2
        return;
    end
    gt_edge=bwperim(inc,8);
    emn=min(est(:));emx=max(est(:));
    if emx<=emn || ~any(gt_edge(:)),return;end
    est_norm=(est-emn)/(emx-emn);
    detected=edge(est_norm); % same MATLAB default as project code
    [rr,cc]=find(inc);
    margin=max(3,round(0.5*max(max(rr)-min(rr)+1,max(cc)-min(cc)+1)));
    bbox=false(size(inc));
    bbox(max(1,min(rr)-margin):min(size(inc,1),max(rr)+margin), ...
         max(1,min(cc)-margin):min(size(inc,2),max(cc)+margin))=true;
    detected=detected & bbox & valid;
    if ~any(detected(:)),return;end
    dx_mm=median(diff(x))*1000;
    dz_mm=median(diff(z))*1000;
    % Exact Euclidean physical distance on the nearly isotropic grid.
    r0=min(dx_mm,dz_mm);
    distance_px=bwdist(gt_edge);
    S.EdgeAccuracy_mm=mean(distance_px(detected))*r0;
    [gx,gz]=gradient(double(est),dx_mm,dz_mm);
    mag=hypot(gx,gz);
    S.EdgeSharpness_mps_per_mm=mean(mag(detected));
end

function auc=calc_auc(q,is_good)
    q=double(q(:)); is_good=logical(is_good(:));
    valid=isfinite(q);
    q=q(valid);is_good=is_good(valid);
    ng=nnz(is_good); nb=nnz(~is_good);
    if ng==0 || nb==0,auc=NaN;return;end
    [v,ix]=sort(q,'ascend'); yy=double(is_good(ix));
    n=numel(v);
    starts=[1;find(diff(v)~=0)+1];
    ends=[starts(2:end)-1;n];
    cumulative=[0;cumsum(yy)];
    count_good=cumulative(ends+1)-cumulative(starts);
    mid_rank=(starts+ends)/2;
    auc=(sum(count_good.*mid_rank)-ng*(ng+1)/2)/(ng*nb);
    auc=max(0,min(1,auc));
end

function fc=top_half_wrong_fraction(q,bad)
    q=double(q(:));bad=double(bad(:));
    n=numel(q);
    if n==0 || any(~isfinite(q)),fc=NaN;return;end
    v=sort(q,'descend');cut=v(ceil(n/2));
    above=q>cut;ties=q==cut;
    if ~any(ties),fc=NaN;return;end
    w_tie=max(0,min(1,(n/2-nnz(above))/nnz(ties)));
    w=double(above)+w_tie*double(ties);
    fc=sum(w.*bad)/sum(w);
end

function draw_detail(out_dir,name,variant,x,z,gt,est,err,Q,RMI,valid,rho,qth,rth)
    f=figure('Color','w','Visible','off','Position',[30 50 1570 830]);
    tiledlayout(f,2,3,'TileSpacing','compact','Padding','compact');
    vmax=max([6.2;gt(:);est(:)]);
    panel(nexttile,x,z,gt,[1 vmax],'Known exact SWS [m/s]');
    panel(nexttile,x,z,est,[1 vmax],'Artificial SWS [m/s]');
    panel(nexttile,x,z,err,[0 max(1,max(err(:)))], ...
        'Absolute SWS error [m/s]');
    qc=Q;qc(~valid)=NaN;
    qr=RMI;qr(~valid)=NaN;
    panel(nexttile,x,z,qc,[0 1],'Correlation Q (analytical u)');
    panel(nexttile,x,z,qr,[0 1],'RMI-1D (analytical u)');
    E=3*rho*est.^2/1000;
    E(~valid)=NaN;
    E(Q<qth | RMI<rth)=NaN;
    panel(nexttile,x,z,E,[0 120], ...
        'Young modulus [kPa] (passes BOTH example thresholds)');
    exportgraphics(f,fullfile(out_dir,[name '_' variant '_six_panel.png']), ...
        'Resolution',150);
    close(f);

    % Three stiffness views to match the existing project presentation.
    stiffness=3*rho*est.^2/1000;
    stiffness(~valid)=NaN;
    corr_masked=stiffness; corr_masked(Q<qth)=NaN;
    rmi_masked=stiffness; rmi_masked(RMI<rth)=NaN;
    max_E=max(120,ceil(max(stiffness(isfinite(stiffness)))/10)*10);
    g=figure('Color','w','Visible','off','Position',[30 80 1500 540]);
    tl=tiledlayout(g,1,3,'TileSpacing','compact','Padding','compact');
    panel(nexttile(tl),x,z,stiffness,[0 max_E],'Original Young modulus [kPa]');
    panel(nexttile(tl),x,z,corr_masked,[0 max_E], ...
        sprintf('Correlation Q >= %.2f (illustrative)',qth));
    panel(nexttile(tl),x,z,rmi_masked,[0 max_E], ...
        sprintf('RMI-1D >= %.2f (illustrative)',rth));
    title(tl,[strrep(name,'_',' ') ' | ' variant ' | same SWS map']);
    exportgraphics(g,fullfile(out_dir,[name '_' variant '_stiffness.png']), ...
        'Resolution',150);
    close(g);
end

function draw_overview(out_dir,names,x,z,maps,color_label,limits,filename,show_fig)
    visibility='off'; if show_fig,visibility='on';end
    f=figure('Color','w','Visible',visibility,'Position',[40 80 1480 750]);
    tl=tiledlayout(f,2,4,'Padding','compact','TileSpacing','compact');
    for i=1:numel(names)
        ax=nexttile(tl);
        panel(ax,x,z,maps{i},limits,strrep(names{i},'_',' '));
    end
    title(tl,['Eight exact SWS phantoms | ' color_label ' | analytical displacement']);
    exportgraphics(f,fullfile(out_dir,filename),'Resolution',160);
    if ~show_fig,close(f);end
end

function panel(ax,x,z,V,lims,ttl)
    h=imagesc(ax,x*1e3,z*1e3,V);
    set(h,'AlphaData',double(isfinite(V)));
    set(ax,'Color',[.93 .93 .93],'YDir','normal');
    axis(ax,'image');
    caxis(ax,lims);
    colormap(ax,parula(256));
    cb=colorbar(ax);
    cb.Label.String='Value';
    xlabel(ax,'x [mm]');ylabel(ax,'z [mm]');
    title(ax,ttl,'Interpreter','none');
end
