function results = analyze_displacement_quality(config)

%% ========================================================================
% ANALYZE_DISPLACEMENT_QUALITY
%
% Generic displacement-quality analysis for synthetic THE phantoms.
%
% INPUT:
%
%   config.data_file
%   config.phantom_case
%   config.results_dir
%   config.Q_threshold
%   config.edge_margin_samples
%   config.run_noise_sweep
%   config.noise_levels_dB
%   config.n_noise_realizations
%
%
% ANALYSIS:
%
%   Ground truth packet averaging
%   Estimated displacement vs GT
%   Q_C = |C - 1|
%   Pearson / Spearman Q_C vs absolute displacement error
%   Q_C threshold analysis
%   Repeated noise sweep
%
%
% IMPORTANT:
%
% disp_gt already represents incremental displacement between consecutive
% PRF samples.
%
% It must NOT be differentiated again.
%
% ========================================================================


%% ========================================================================
% 1. Configuration
% ========================================================================

Q_threshold = ...
    config.Q_threshold;


edge_margin = ...
    config.edge_margin_samples;


noise_levels_dB = ...
    config.noise_levels_dB;


n_realizations = ...
    config.n_noise_realizations;


fprintf('\n');
fprintf('------------------------------------------------------------\n');
fprintf('DISPLACEMENT QUALITY: %s\n', ...
    upper(config.phantom_case));
fprintf('------------------------------------------------------------\n');


%% ========================================================================
% 2. Load dataset
% ========================================================================

data = ...
    load( ...
        config.data_file);


%% ========================================================================
% 3. Check required variables
% ========================================================================

required_variables = ...
    { ...
    'b_data', ...
    'disp_gt', ...
    'displacement_estimation_autocorr', ...
    'quality_indicator_autocorr' ...
    };


for k = 1:numel(required_variables)

    if ~isfield(data,required_variables{k})

        error( ...
            'Dataset is missing variable: %s', ...
            required_variables{k});

    end

end


b_data = ...
    data.b_data;


disp_gt = ...
    double( ...
        data.disp_gt);


displacement_object = ...
    data.displacement_estimation_autocorr;


quality_indicator = ...
    data.quality_indicator_autocorr;


%% ========================================================================
% 4. Autocorrelation parameters
% ========================================================================

if isfield(data,'autocorr_params')

    autocorr_params = ...
        data.autocorr_params;

else

    warning( ...
        ['autocorr_params not found. ' ...
         'Using established project defaults.']);


    autocorr_params.z_gate = ...
        4;


    autocorr_params.x_gate = ...
        2;


    autocorr_params.packet_size = ...
        4;

end


packet_size = ...
    autocorr_params.packet_size;


packet_intervals = ...
    packet_size - 1;


N_frames = ...
    size(disp_gt,3) - ...
    packet_intervals + 1;


fprintf('GT size:                 %s\n', ...
    mat2str(size(disp_gt)));


fprintf('Estimator size:          %s\n', ...
    mat2str(size(displacement_object.data)));


fprintf('Quality size:            %s\n', ...
    mat2str(size(quality_indicator)));


fprintf('Packet size:             %d\n', ...
    packet_size);


fprintf('Expected output frames:  %d\n', ...
    N_frames);


%% ========================================================================
% 5. Ground-truth packet averaging
% ========================================================================
%
% packet_size = 4 RF frames
%
% therefore corresponds to:
%
%       3 incremental GT displacement intervals
%
% ========================================================================

gt_packet = ...
    zeros( ...
        size(disp_gt,1), ...
        size(disp_gt,2), ...
        N_frames);


for k = 1:N_frames

    gt_packet(:,:,k) = ...
        mean( ...
            disp_gt(:,:, ...
            k:k+packet_intervals-1), ...
            3);

end


%% ========================================================================
% 6. Estimator dimensions
% ========================================================================

Nz = ...
    length( ...
        b_data.scan.z_axis);


Nx = ...
    length( ...
        b_data.scan.x_axis);


N_est = ...
    size( ...
        displacement_object.data, ...
        4);


if N_est ~= N_frames

    error( ...
        ['Estimator/GT frame mismatch.\n' ...
         'Estimator = %d\nGT packets = %d'], ...
        N_est, ...
        N_frames);

end


%% ========================================================================
% 7. Reshape estimated displacement
% ========================================================================

disp_est = ...
    reshape( ...
        double( ...
            displacement_object.data(:,1,1,:)), ...
        Nz, ...
        Nx, ...
        N_est);


%% ------------------------------------------------------------------------
% Sign convention
% ------------------------------------------------------------------------
%
% The autocorrelation displacement convention in this pipeline is opposite
% to the k-Wave GT convention.
% ========================================================================

disp_est = ...
    -disp_est;


%% ========================================================================
% 8. Reshape normalized autocorrelation C
% ========================================================================

C_est = ...
    reshape( ...
        double( ...
            quality_indicator(:,1,1,:)), ...
        Nz, ...
        Nx, ...
        N_est);


%% ========================================================================
% 9. Spatial coordinates
% ========================================================================

x_est = ...
    double( ...
        b_data.scan.x_axis(:).');


z_est = ...
    double( ...
        b_data.scan.z_axis(:));


%% ------------------------------------------------------------------------
% Ground-truth displacement grid
% ------------------------------------------------------------------------
%
% The current synthetic GT displacement matrices span the same imaging
% region but at lower spatial sampling density.
% ========================================================================

x_gt = ...
    linspace( ...
        x_est(1), ...
        x_est(end), ...
        size(gt_packet,2));


z_gt = ...
    linspace( ...
        z_est(1), ...
        z_est(end), ...
        size(gt_packet,1));


[X_gt,Z_gt] = ...
    meshgrid( ...
        x_gt, ...
        z_gt);


%% ========================================================================
% 10. Interpolate estimate and C to GT grid
% ========================================================================

disp_interp = ...
    nan( ...
        size(gt_packet));


C_interp = ...
    nan( ...
        size(gt_packet));


for k = 1:N_frames

    disp_interp(:,:,k) = ...
        interp2( ...
            x_est, ...
            z_est, ...
            disp_est(:,:,k), ...
            X_gt, ...
            Z_gt, ...
            'linear', ...
            NaN);


    C_interp(:,:,k) = ...
        interp2( ...
            x_est, ...
            z_est, ...
            C_est(:,:,k), ...
            X_gt, ...
            Z_gt, ...
            'linear', ...
            NaN);

end


%% ========================================================================
% 11. Candidate reliability metric
% ========================================================================

Q_C = ...
    abs( ...
        C_interp - 1);


%% ========================================================================
% 12. Spatial evaluation ROI
% ========================================================================

spatial_mask = ...
    false( ...
        size(gt_packet,1), ...
        size(gt_packet,2));


spatial_mask( ...
    1+edge_margin:end-edge_margin, ...
    1+edge_margin:end-edge_margin) = ...
    true;


spatial_mask_3D = ...
    repmat( ...
        spatial_mask, ...
        1, ...
        1, ...
        N_frames);


valid_mask = ...
    spatial_mask_3D & ...
    isfinite(gt_packet) & ...
    isfinite(disp_interp) & ...
    isfinite(Q_C);


%% ========================================================================
% 13. Baseline samples
% ========================================================================

gt_valid_um = ...
    gt_packet(valid_mask) ...
    * 1e6;


est_valid_um = ...
    disp_interp(valid_mask) ...
    * 1e6;


Q_valid = ...
    Q_C(valid_mask);


error_um = ...
    est_valid_um - ...
    gt_valid_um;


abs_error_um = ...
    abs(error_um);


%% ========================================================================
% 14. Baseline accuracy metrics
% ========================================================================

baseline = ...
    struct();


baseline.N = ...
    numel(error_um);


baseline.bias_um = ...
    mean(error_um);


baseline.MAE_um = ...
    mean(abs_error_um);


baseline.RMSE_um = ...
    sqrt( ...
        mean( ...
            error_um.^2));


baseline.median_abs_error_um = ...
    median(abs_error_um);


baseline.P95_abs_error_um = ...
    prctile(abs_error_um,95);


baseline.P99_abs_error_um = ...
    prctile(abs_error_um,99);


baseline.correlation = ...
    corr( ...
        gt_valid_um, ...
        est_valid_um, ...
        'Rows', ...
        'complete');


%% ========================================================================
% 15. Q_C statistics
% ========================================================================

baseline.median_Q = ...
    median(Q_valid);


baseline.mean_Q = ...
    mean(Q_valid);


baseline.P95_Q = ...
    prctile(Q_valid,95);


baseline.P99_Q = ...
    prctile(Q_valid,99);


baseline.pearson_Q_error = ...
    corr( ...
        Q_valid, ...
        abs_error_um, ...
        'Type', ...
        'Pearson', ...
        'Rows', ...
        'complete');


baseline.spearman_Q_error = ...
    corr( ...
        Q_valid, ...
        abs_error_um, ...
        'Type', ...
        'Spearman', ...
        'Rows', ...
        'complete');


%% ========================================================================
% 16. Q_C threshold analysis
% ========================================================================

accepted = ...
    Q_valid <= ...
    Q_threshold;


rejected = ...
    Q_valid > ...
    Q_threshold;


baseline.retained_percent = ...
    100 * ...
    mean(accepted);


if any(accepted)

    gated_error = ...
        error_um(accepted);


    baseline.gated_RMSE_um = ...
        sqrt( ...
            mean( ...
                gated_error.^2));


    baseline.gated_MAE_um = ...
        mean( ...
            abs(gated_error));

else

    baseline.gated_RMSE_um = ...
        NaN;


    baseline.gated_MAE_um = ...
        NaN;

end


if any(rejected)

    rejected_error = ...
        error_um(rejected);


    baseline.rejected_RMSE_um = ...
        sqrt( ...
            mean( ...
                rejected_error.^2));

else

    baseline.rejected_RMSE_um = ...
        NaN;

end


%% ========================================================================
% 17. Print baseline
% ========================================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('BASELINE DISPLACEMENT QUALITY\n');
fprintf('============================================================\n');


fprintf('Valid samples:             %d\n', ...
    baseline.N);


fprintf('RMSE:                      %.5f um\n', ...
    baseline.RMSE_um);


fprintf('MAE:                       %.5f um\n', ...
    baseline.MAE_um);


fprintf('Median abs. error:         %.5f um\n', ...
    baseline.median_abs_error_um);


fprintf('Bias:                      %.5f um\n', ...
    baseline.bias_um);


fprintf('Estimate-GT correlation:   %.5f\n', ...
    baseline.correlation);


fprintf('\n');


fprintf('Median Q_C:                %.7f\n', ...
    baseline.median_Q);


fprintf('Pearson(Q_C,|error|):      %.5f\n', ...
    baseline.pearson_Q_error);


fprintf('Spearman(Q_C,|error|):     %.5f\n', ...
    baseline.spearman_Q_error);


fprintf('Q_C <= %.3f retained:      %.2f %%\n', ...
    Q_threshold, ...
    baseline.retained_percent);


fprintf('Gated RMSE:                %.5f um\n', ...
    baseline.gated_RMSE_um);


fprintf('Rejected RMSE:             %.5f um\n', ...
    baseline.rejected_RMSE_um);


fprintf('============================================================\n');


%% ========================================================================
% 18. Baseline summary table
% ========================================================================

baseline_table = ...
    table( ...
        baseline.N, ...
        baseline.RMSE_um, ...
        baseline.MAE_um, ...
        baseline.median_abs_error_um, ...
        baseline.bias_um, ...
        baseline.correlation, ...
        baseline.median_Q, ...
        baseline.mean_Q, ...
        baseline.pearson_Q_error, ...
        baseline.spearman_Q_error, ...
        baseline.retained_percent, ...
        baseline.gated_RMSE_um, ...
        baseline.rejected_RMSE_um, ...
        'VariableNames', ...
        { ...
        'N', ...
        'RMSE_um', ...
        'MAE_um', ...
        'MedianAbsError_um', ...
        'Bias_um', ...
        'EstimateGTCorrelation', ...
        'Median_QC', ...
        'Mean_QC', ...
        'Pearson_QC_Error', ...
        'Spearman_QC_Error', ...
        'Retained_percent', ...
        'Gated_RMSE_um', ...
        'Rejected_RMSE_um'});


%% ========================================================================
% 19. Noise sweep
% ========================================================================

noise_results = ...
    [];


noise_summary = ...
    table();


if config.run_noise_sweep

    if ~isfield(data,'channel_data')

        warning( ...
            ['channel_data is missing. ' ...
             'Skipping repeated noise sweep.']);

    else

        fprintf('\n');
        fprintf('============================================================\n');
        fprintf('REPEATED DISPLACEMENT NOISE SWEEP\n');
        fprintf('============================================================\n');


        channel_data = ...
            data.channel_data;


        original_b_data = ...
            b_data.data;


        signal_power = ...
            mean( ...
                abs( ...
                    double(original_b_data(:))).^2, ...
                'omitnan');


        n_conditions = ...
            numel(noise_levels_dB);


        RMSE = ...
            nan( ...
                n_conditions, ...
                n_realizations);


        Corr = ...
            nan( ...
                n_conditions, ...
                n_realizations);


        MedianQ = ...
            nan( ...
                n_conditions, ...
                n_realizations);


        Pearson = ...
            nan( ...
                n_conditions, ...
                n_realizations);


        Spearman = ...
            nan( ...
                n_conditions, ...
                n_realizations);


        GatedRMSE = ...
            nan( ...
                n_conditions, ...
                n_realizations);


        Retained = ...
            nan( ...
                n_conditions, ...
                n_realizations);


        for s = 1:n_conditions

            snr_dB = ...
                noise_levels_dB(s);


            noise_power = ...
                signal_power / ...
                10^(snr_dB/10);


            fprintf('\nSNR = %d dB\n', ...
                snr_dB);


            for r = 1:n_realizations

                %% --------------------------------------------------------
                % Reproducible realization
                % ---------------------------------------------------------

                rng( ...
                    1000*s+r, ...
                    'twister');


                %% --------------------------------------------------------
                % AWGN
                % ---------------------------------------------------------

                if isreal(original_b_data)

                    noise = ...
                        sqrt(noise_power) .* ...
                        randn( ...
                            size(original_b_data), ...
                            'like', ...
                            original_b_data);

                else

                    noise_real = ...
                        randn( ...
                            size(original_b_data), ...
                            'like', ...
                            real(original_b_data));


                    noise_imag = ...
                        randn( ...
                            size(original_b_data), ...
                            'like', ...
                            real(original_b_data));


                    noise = ...
                        sqrt(noise_power/2) .* ...
                        complex( ...
                            noise_real, ...
                            noise_imag);

                end


                %% --------------------------------------------------------
                % Noisy beamformed data
                % ---------------------------------------------------------

                b_data.data = ...
                    original_b_data + ...
                    noise;


                %% --------------------------------------------------------
                % Autocorrelation estimator
                % ---------------------------------------------------------

                estimator = ...
                    postprocess.autocorrelation_displacement_estimation();


                estimator.channel_data = ...
                    channel_data;


                estimator.input = ...
                    b_data;


                estimator.z_gate = ...
                    autocorr_params.z_gate;


                estimator.x_gate = ...
                    autocorr_params.x_gate;


                estimator.packet_size = ...
                    autocorr_params.packet_size;


                displacement_noisy = ...
                    estimator.go();


                quality_noisy = ...
                    estimator.quality_indicator;


                %% --------------------------------------------------------
                % Evaluate current realization
                % ---------------------------------------------------------

                m = ...
                    evaluate_current_run( ...
                        displacement_noisy, ...
                        quality_noisy, ...
                        gt_packet, ...
                        x_est, ...
                        z_est, ...
                        X_gt, ...
                        Z_gt, ...
                        spatial_mask_3D, ...
                        Nz, ...
                        Nx, ...
                        Q_threshold);


                RMSE(s,r) = ...
                    m.RMSE_um;


                Corr(s,r) = ...
                    m.correlation;


                MedianQ(s,r) = ...
                    m.median_Q;


                Pearson(s,r) = ...
                    m.pearson_Q_error;


                Spearman(s,r) = ...
                    m.spearman_Q_error;


                GatedRMSE(s,r) = ...
                    m.gated_RMSE_um;


                Retained(s,r) = ...
                    m.retained_percent;


                fprintf( ...
                    ['  %2d/%2d | RMSE %.4f um | ' ...
                     'Q %.5f | retained %.2f %%\n'], ...
                    r, ...
                    n_realizations, ...
                    m.RMSE_um, ...
                    m.median_Q, ...
                    m.retained_percent);

            end

        end


        %% ---------------------------------------------------------------
        % Restore original data
        % ---------------------------------------------------------

        b_data.data = ...
            original_b_data;


        %% ---------------------------------------------------------------
        % Summary
        % ---------------------------------------------------------

        Condition = ...
            string( ...
                noise_levels_dB(:)) + ...
            " dB";


        RMSE_mean = ...
            mean(RMSE,2,'omitnan');


        RMSE_std = ...
            std(RMSE,0,2,'omitnan');


        Corr_mean = ...
            mean(Corr,2,'omitnan');


        Corr_std = ...
            std(Corr,0,2,'omitnan');


        MedianQ_mean = ...
            mean(MedianQ,2,'omitnan');


        MedianQ_std = ...
            std(MedianQ,0,2,'omitnan');


        Pearson_mean = ...
            mean(Pearson,2,'omitnan');


        Pearson_std = ...
            std(Pearson,0,2,'omitnan');


        Spearman_mean = ...
            mean(Spearman,2,'omitnan');


        Spearman_std = ...
            std(Spearman,0,2,'omitnan');


        GatedRMSE_mean = ...
            mean(GatedRMSE,2,'omitnan');


        GatedRMSE_std = ...
            std(GatedRMSE,0,2,'omitnan');


        Retained_mean = ...
            mean(Retained,2,'omitnan');


        Retained_std = ...
            std(Retained,0,2,'omitnan');


        noise_summary = ...
            table( ...
                Condition, ...
                RMSE_mean, ...
                RMSE_std, ...
                Corr_mean, ...
                Corr_std, ...
                MedianQ_mean, ...
                MedianQ_std, ...
                Pearson_mean, ...
                Pearson_std, ...
                Spearman_mean, ...
                Spearman_std, ...
                GatedRMSE_mean, ...
                GatedRMSE_std, ...
                Retained_mean, ...
                Retained_std);


        fprintf('\n');
        fprintf('============================================================\n');
        fprintf('NOISE SWEEP SUMMARY\n');
        fprintf('============================================================\n');


        disp(noise_summary);


        noise_results.RMSE = ...
            RMSE;


        noise_results.Correlation = ...
            Corr;


        noise_results.MedianQ = ...
            MedianQ;


        noise_results.Pearson = ...
            Pearson;


        noise_results.Spearman = ...
            Spearman;


        noise_results.GatedRMSE = ...
            GatedRMSE;


        noise_results.Retained = ...
            Retained;

    end

end


%% ========================================================================
% 20. Save consolidated results
% ========================================================================

results = ...
    struct();


results.phantom_case = ...
    config.phantom_case;


results.baseline = ...
    baseline;


results.baseline_table = ...
    baseline_table;


results.noise_results = ...
    noise_results;


results.noise_summary = ...
    noise_summary;


results.Q_threshold = ...
    Q_threshold;


results.edge_margin_samples = ...
    edge_margin;


save_file = ...
    fullfile( ...
        config.results_dir, ...
        sprintf( ...
            '%s_displacement_quality_results.mat', ...
            config.phantom_case));


save( ...
    save_file, ...
    'results', ...
    '-v7.3');


baseline_csv = ...
    fullfile( ...
        config.results_dir, ...
        sprintf( ...
            '%s_displacement_baseline.csv', ...
            config.phantom_case));


writetable( ...
    baseline_table, ...
    baseline_csv);


if ~isempty(noise_summary)

    noise_csv = ...
        fullfile( ...
            config.results_dir, ...
            sprintf( ...
                '%s_displacement_noise_summary.csv', ...
                config.phantom_case));


    writetable( ...
        noise_summary, ...
        noise_csv);

end


fprintf('\nSaved consolidated displacement results:\n');
fprintf('%s\n',save_file);


%% ========================================================================
% 21. Basic figures
% ========================================================================

figure;

scatter( ...
    Q_valid, ...
    abs_error_um, ...
    4, ...
    'filled');


xlabel('$Q_C = |C-1|$', ...
    'Interpreter', ...
    'latex');


ylabel('Absolute displacement error [$\mu$m]', ...
    'Interpreter', ...
    'latex');


title( ...
    sprintf( ...
        '%s: Q_C vs displacement error', ...
        strrep(config.phantom_case,'_',' ')));


grid on;


if ~isempty(noise_summary)

    figure;

    errorbar( ...
        noise_levels_dB, ...
        noise_summary.RMSE_mean, ...
        noise_summary.RMSE_std, ...
        'o-', ...
        'LineWidth', ...
        1.5);


    set(gca,'XDir','reverse');


    xlabel('SNR [dB]');


    ylabel('Displacement RMSE [$\mu$m]', ...
        'Interpreter', ...
        'latex');


    title( ...
        sprintf( ...
            '%s: noise robustness', ...
            strrep(config.phantom_case,'_',' ')));


    grid on;

end

end


%% ========================================================================
% LOCAL FUNCTION
% ========================================================================

function metrics = ...
    evaluate_current_run( ...
        displacement_object, ...
        quality_indicator, ...
        gt_packet, ...
        x_est, ...
        z_est, ...
        X_gt, ...
        Z_gt, ...
        spatial_mask_3D, ...
        Nz, ...
        Nx, ...
        Q_threshold)


    N_frames = ...
        size(gt_packet,3);


    %% --------------------------------------------------------------------
    % Estimated displacement
    % ---------------------------------------------------------------------

    disp_est = ...
        reshape( ...
            double( ...
                displacement_object.data(:,1,1,:)), ...
            Nz, ...
            Nx, ...
            N_frames);


    disp_est = ...
        -disp_est;


    %% --------------------------------------------------------------------
    % C
    % ---------------------------------------------------------------------

    C_est = ...
        reshape( ...
            double( ...
                quality_indicator(:,1,1,:)), ...
            Nz, ...
            Nx, ...
            N_frames);


    %% --------------------------------------------------------------------
    % Interpolate
    % ---------------------------------------------------------------------

    disp_interp = ...
        nan( ...
            size(gt_packet));


    C_interp = ...
        nan( ...
            size(gt_packet));


    for k = 1:N_frames

        disp_interp(:,:,k) = ...
            interp2( ...
                x_est, ...
                z_est, ...
                disp_est(:,:,k), ...
                X_gt, ...
                Z_gt, ...
                'linear', ...
                NaN);


        C_interp(:,:,k) = ...
            interp2( ...
                x_est, ...
                z_est, ...
                C_est(:,:,k), ...
                X_gt, ...
                Z_gt, ...
                'linear', ...
                NaN);

    end


    %% --------------------------------------------------------------------
    % Candidate metric
    % ---------------------------------------------------------------------

    Q_C = ...
        abs( ...
            C_interp - 1);


    %% --------------------------------------------------------------------
    % Valid samples
    % ---------------------------------------------------------------------

    valid = ...
        spatial_mask_3D & ...
        isfinite(gt_packet) & ...
        isfinite(disp_interp) & ...
        isfinite(Q_C);


    gt_um = ...
        gt_packet(valid) ...
        * 1e6;


    est_um = ...
        disp_interp(valid) ...
        * 1e6;


    q = ...
        Q_C(valid);


    error_um = ...
        est_um - ...
        gt_um;


    abs_error_um = ...
        abs(error_um);


    %% --------------------------------------------------------------------
    % Metrics
    % ---------------------------------------------------------------------

    metrics.RMSE_um = ...
        sqrt( ...
            mean( ...
                error_um.^2));


    metrics.correlation = ...
        corr( ...
            gt_um, ...
            est_um, ...
            'Rows', ...
            'complete');


    metrics.median_Q = ...
        median(q);


    metrics.pearson_Q_error = ...
        corr( ...
            q, ...
            abs_error_um, ...
            'Type', ...
            'Pearson', ...
            'Rows', ...
            'complete');


    metrics.spearman_Q_error = ...
        corr( ...
            q, ...
            abs_error_um, ...
            'Type', ...
            'Spearman', ...
            'Rows', ...
            'complete');


    accepted = ...
        q <= ...
        Q_threshold;


    metrics.retained_percent = ...
        100 * ...
        mean(accepted);


    if any(accepted)

        metrics.gated_RMSE_um = ...
            sqrt( ...
                mean( ...
                    error_um(accepted).^2));

    else

        metrics.gated_RMSE_um = ...
            NaN;

    end

end