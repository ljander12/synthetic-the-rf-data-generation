%% Metric summary figures
%
% Summary plots for:
%   1) Stiffness contrast sweep:
%      low_contrast -> chaoran_baseline -> high_contrast
%
%   2) Exploratory inclusion-size comparison:
%      chaoran_baseline -> large_inclusions
%
% All values are loaded from saved CSV result files.
% No quality metrics are recomputed in this script.

clear;
clc;
close all;

%% ========================================================================
% Repository paths
% ========================================================================

analysis_dir = fileparts(mfilename('fullpath'));
repo_dir = fileparts(analysis_dir);

results_dir = fullfile(repo_dir, 'Results');

output_dir = fullfile( ...
    results_dir, ...
    'metric_summary');

if ~isfolder(output_dir)
    mkdir(output_dir);
end

%% ========================================================================
% Result files
% ========================================================================

low_file = fullfile( ...
    results_dir, ...
    'low_contrast', ...
    'low_contrast_SWS_baseline.csv');

baseline_file = fullfile( ...
    results_dir, ...
    'chaoran_baseline', ...
    'chaoran_baseline_SWS_baseline.csv');

high_file = fullfile( ...
    results_dir, ...
    'high_contrast', ...
    'high_contrast_SWS_baseline.csv');

large_file = fullfile( ...
    results_dir, ...
    'large_inclusions', ...
    'large_inclusions_SWS_baseline.csv');

%% Check that all files exist

required_files = { ...
    low_file, ...
    baseline_file, ...
    high_file, ...
    large_file};

for k = 1:numel(required_files)

    if ~isfile(required_files{k})
        error( ...
            'Required result file not found:\n%s', ...
            required_files{k});
    end

end

%% ========================================================================
% Load results
% ========================================================================

low = readtable(low_file);
baseline = readtable(baseline_file);
high = readtable(high_file);
large = readtable(large_file);

%% ========================================================================
% Contrast sweep data
% ========================================================================

contrast_case_names = { ...
    'Low', ...
    'Baseline', ...
    'High'};

c_incl_gt = [ ...
    low.GT_Inclusion_SWS_mps, ...
    baseline.GT_Inclusion_SWS_mps, ...
    high.GT_Inclusion_SWS_mps];

c_bkg_gt = [ ...
    low.GT_Background_SWS_mps, ...
    baseline.GT_Background_SWS_mps, ...
    high.GT_Background_SWS_mps];

c_incl_est = [ ...
    low.InclusionMean_mps, ...
    baseline.InclusionMean_mps, ...
    high.InclusionMean_mps];

true_contrast = [ ...
    low.TrueContrast_mps, ...
    baseline.TrueContrast_mps, ...
    high.TrueContrast_mps];

relative_bias = [ ...
    low.InclusionRelativeBias_percent, ...
    baseline.InclusionRelativeBias_percent, ...
    high.InclusionRelativeBias_percent];

contrast_recovery = [ ...
    low.ContrastRecovery, ...
    baseline.ContrastRecovery, ...
    high.ContrastRecovery];

CNR = [ ...
    low.CNR, ...
    baseline.CNR, ...
    high.CNR];

gCNR_direct = [ ...
    low.DirectKDE_gCNR, ...
    baseline.DirectKDE_gCNR, ...
    high.DirectKDE_gCNR];

%% ========================================================================
% FIGURE 1
% Quantitative SWS reconstruction
% ========================================================================

figure;

plot( ...
    c_incl_gt, ...
    c_incl_est, ...
    '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

hold on;

plot( ...
    [min(c_incl_gt), max(c_incl_gt)], ...
    [min(c_incl_gt), max(c_incl_gt)], ...
    '--', ...
    'LineWidth', 1.5);

hold off;

grid on;
box on;

xlabel('Ground-truth inclusion SWS [m/s]');
ylabel('Estimated inclusion SWS [m/s]');

title('Quantitative SWS reconstruction');

legend( ...
    'Phase-gradient estimate', ...
    'Ideal reconstruction', ...
    'Location', 'northwest');

for k = 1:numel(contrast_case_names)

    text( ...
        c_incl_gt(k), ...
        c_incl_est(k), ...
        ['  ' contrast_case_names{k}], ...
        'VerticalAlignment', 'bottom');

end

exportgraphics( ...
    gcf, ...
    fullfile( ...
        output_dir, ...
        'contrast_sweep_estimated_vs_ground_truth.png'), ...
    'Resolution', 300);

%% ========================================================================
% FIGURE 2
% Detectability versus stiffness contrast
% ========================================================================

figure;

yyaxis left

plot( ...
    true_contrast, ...
    CNR, ...
    '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

ylabel('CNR');
ylim([0 1.8]);

yyaxis right

plot( ...
    true_contrast, ...
    gCNR_direct, ...
    '-s', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

ylabel('Direct-KDE gCNR');
ylim([0 1]);

grid on;
box on;

xlabel('Ground-truth SWS contrast [m/s]');
title('Detectability versus stiffness contrast');

legend( ...
    'CNR', ...
    'Direct-KDE gCNR (exploratory)', ...
    'Location', 'best');

for k = 1:numel(contrast_case_names)

    text( ...
        true_contrast(k), ...
        gCNR_direct(k), ...
        ['  ' contrast_case_names{k}], ...
        'VerticalAlignment', 'bottom');

end

exportgraphics( ...
    gcf, ...
    fullfile( ...
        output_dir, ...
        'contrast_sweep_detectability_metrics.png'), ...
    'Resolution', 300);

%% ========================================================================
% FIGURE 3
% Quantitative error versus stiffness contrast
% ========================================================================

figure;

plot( ...
    true_contrast, ...
    relative_bias, ...
    '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

hold on;

yline(0, '--');

hold off;

grid on;
box on;

xlabel('Ground-truth SWS contrast [m/s]');
ylabel('Inclusion relative bias [%]');

title('Quantitative error versus stiffness contrast');

for k = 1:numel(contrast_case_names)

    text( ...
        true_contrast(k), ...
        relative_bias(k), ...
        sprintf( ...
            '  %s (%.1f%%)', ...
            contrast_case_names{k}, ...
            relative_bias(k)), ...
        'VerticalAlignment', 'bottom');

end

exportgraphics( ...
    gcf, ...
    fullfile( ...
        output_dir, ...
        'contrast_sweep_relative_bias.png'), ...
    'Resolution', 300);

%% ========================================================================
% Save contrast-sweep summary table
% ========================================================================

contrast_summary = table( ...
    contrast_case_names.', ...
    c_incl_gt.', ...
    c_bkg_gt.', ...
    c_incl_est.', ...
    true_contrast.', ...
    relative_bias.', ...
    contrast_recovery.', ...
    CNR.', ...
    gCNR_direct.', ...
    'VariableNames', { ...
        'Case', ...
        'GT_Inclusion_SWS_mps', ...
        'GT_Background_SWS_mps', ...
        'Estimated_Inclusion_SWS_mps', ...
        'GT_Contrast_mps', ...
        'InclusionRelativeBias_percent', ...
        'ContrastRecovery', ...
        'CNR', ...
        'DirectKDE_gCNR'});

writetable( ...
    contrast_summary, ...
    fullfile( ...
        output_dir, ...
        'contrast_sweep_metric_summary.csv'));

%% ========================================================================
% Inclusion-size comparison
% Baseline vs large inclusions
% ========================================================================

size_case_names = { ...
    'Baseline', ...
    'Large inclusions'};

size_incl_mean = [ ...
    baseline.InclusionMean_mps, ...
    large.InclusionMean_mps];

size_incl_gt = [ ...
    baseline.GT_Inclusion_SWS_mps, ...
    large.GT_Inclusion_SWS_mps];

size_bkg_mean = [ ...
    baseline.BackgroundMean_mps, ...
    large.BackgroundMean_mps];

size_bkg_gt = [ ...
    baseline.GT_Background_SWS_mps, ...
    large.GT_Background_SWS_mps];

size_incl_bias = [ ...
    baseline.InclusionRelativeBias_percent, ...
    large.InclusionRelativeBias_percent];

size_bkg_bias = [ ...
    baseline.BackgroundRelativeBias_percent, ...
    large.BackgroundRelativeBias_percent];

size_global_rmse = [ ...
    baseline.GlobalRMSE_mps, ...
    large.GlobalRMSE_mps];

size_contrast_recovery = [ ...
    baseline.ContrastRecovery, ...
    large.ContrastRecovery];

size_CNR = [ ...
    baseline.CNR, ...
    large.CNR];

size_gCNR = [ ...
    baseline.DirectKDE_gCNR, ...
    large.DirectKDE_gCNR];

%% ========================================================================
% FIGURE 4
% Exploratory inclusion-size comparison
% ========================================================================

figure;

tiledlayout( ...
    2, ...
    3, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

%% Tile 1 - Inclusion SWS

nexttile;

bar( ...
    [ ...
        size_incl_mean(:), ...
        size_incl_gt(:) ...
    ]);

set(gca, ...
    'XTick', 1:2, ...
    'XTickLabel', size_case_names);

ylabel('SWS [m/s]');
title('Inclusion SWS');

legend( ...
    'Estimated', ...
    'Ground truth', ...
    'Location', 'best');

grid on;
box on;

%% Tile 2 - Background SWS

nexttile;

bar( ...
    [ ...
        size_bkg_mean(:), ...
        size_bkg_gt(:) ...
    ]);

set(gca, ...
    'XTick', 1:2, ...
    'XTickLabel', size_case_names);

ylabel('SWS [m/s]');
title('Background SWS');

legend( ...
    'Estimated', ...
    'Ground truth', ...
    'Location', 'best');

grid on;
box on;

%% Tile 3 - Regional relative bias

nexttile;

bar( ...
    [ ...
        size_incl_bias(:), ...
        size_bkg_bias(:) ...
    ]);

hold on;

yline(0, '--');

hold off;

set(gca, ...
    'XTick', 1:2, ...
    'XTickLabel', size_case_names);

ylabel('Relative bias [%]');
title('Regional quantitative bias');

legend( ...
    'Inclusion', ...
    'Background', ...
    'Location', 'best');

grid on;
box on;

%% Tile 4 - Global RMSE

nexttile;

bar(size_global_rmse);

set(gca, ...
    'XTick', 1:2, ...
    'XTickLabel', size_case_names);

ylabel('RMSE [m/s]');
title('Global reconstruction error');

grid on;
box on;

%% Tile 5 - Contrast recovery

nexttile;

bar(size_contrast_recovery);

hold on;

yline( ...
    1, ...
    '--', ...
    'Ideal');

hold off;

set(gca, ...
    'XTick', 1:2, ...
    'XTickLabel', size_case_names);

ylabel('Contrast recovery');
title('Recovered SWS contrast');

ylim([0 1]);

grid on;
box on;

%% Tile 6 - Detectability

nexttile;

bar( ...
    [ ...
        size_CNR(:), ...
        size_gCNR(:) ...
    ]);

set(gca, ...
    'XTick', 1:2, ...
    'XTickLabel', size_case_names);

ylabel('Metric value');
title('Detectability');

legend( ...
    'CNR', ...
    'Direct-KDE gCNR', ...
    'Location', 'best');

grid on;
box on;

sgtitle( ...
    'Exploratory effect of inclusion size on SWS quality metrics');

exportgraphics( ...
    gcf, ...
    fullfile( ...
        output_dir, ...
        'baseline_vs_large_inclusions_metrics.png'), ...
    'Resolution', 300);

%% ========================================================================
% Save size-comparison summary table
% ========================================================================

size_summary = table( ...
    size_case_names.', ...
    size_incl_gt.', ...
    size_incl_mean.', ...
    size_incl_bias.', ...
    size_bkg_gt.', ...
    size_bkg_mean.', ...
    size_bkg_bias.', ...
    size_global_rmse.', ...
    size_contrast_recovery.', ...
    size_CNR.', ...
    size_gCNR.', ...
    'VariableNames', { ...
        'Case', ...
        'GT_Inclusion_SWS_mps', ...
        'Estimated_Inclusion_SWS_mps', ...
        'InclusionRelativeBias_percent', ...
        'GT_Background_SWS_mps', ...
        'Estimated_Background_SWS_mps', ...
        'BackgroundRelativeBias_percent', ...
        'GlobalRMSE_mps', ...
        'ContrastRecovery', ...
        'CNR', ...
        'DirectKDE_gCNR'});

writetable( ...
    size_summary, ...
    fullfile( ...
        output_dir, ...
        'baseline_vs_large_inclusions_summary.csv'));

%% ========================================================================
% Command-window summary
% ========================================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('METRIC SUMMARY\n');
fprintf('============================================================\n');

fprintf('\nCONTRAST SWEEP\n');
disp(contrast_summary);

fprintf('\nBASELINE VS LARGE INCLUSIONS\n');
disp(size_summary);

fprintf('\nFigures and tables saved to:\n');
fprintf('%s\n', output_dir);

fprintf('============================================================\n');