%% Contrast sweep - metric summary
clear;
clc;
close all;

%% Results from low / baseline / high contrast

case_names = {'Low', 'Baseline', 'High'};

c_bkg_gt = 2.32;

c_incl_gt = [ ...
    3.00, ...
    4.67, ...
    6.00];

c_incl_est = [ ...
    2.5251, ...
    2.7894, ...
    2.8905];

CNR = [ ...
    0.3756, ...
    1.4454, ...
    1.7688];

gCNR_direct = [ ...
    0.8330, ...
    0.9271, ...
    0.9322];

relative_bias = ...
    100 .* (c_incl_est - c_incl_gt) ./ c_incl_gt;

true_contrast = ...
    c_incl_gt - c_bkg_gt;

%% Output directory

analysis_dir = fileparts(mfilename('fullpath'));
repo_dir = fileparts(analysis_dir);

output_dir = fullfile( ...
    repo_dir, ...
    'Results', ...
    'metric_summary');

if ~isfolder(output_dir)
    mkdir(output_dir);
end

%% ================================================================
% Figure 1 - Quantitative SWS accuracy
% ================================================================

figure;

plot( ...
    c_incl_gt, ...
    c_incl_est, ...
    '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

hold on;

plot( ...
    [min(c_incl_gt) max(c_incl_gt)], ...
    [min(c_incl_gt) max(c_incl_gt)], ...
    '--', ...
    'LineWidth', 1.5);

hold off;

grid on;
box on;

xlabel('Ground-truth inclusion SWS [m/s]');
ylabel('Estimated inclusion SWS [m/s]');

title('Quantitative SWS reconstruction');

legend( ...
    'Phase-gradient estimate', ...
    'Ideal reconstruction', ...
    'Location', 'northwest');

for k = 1:numel(case_names)

    text( ...
        c_incl_gt(k), ...
        c_incl_est(k), ...
        ['  ' case_names{k}], ...
        'VerticalAlignment', 'bottom');

end

exportgraphics( ...
    gcf, ...
    fullfile(output_dir, ...
    'contrast_sweep_estimated_vs_ground_truth.png'), ...
    'Resolution', 300);

%% ================================================================
% Figure 2 - Detectability metrics
% ================================================================

figure;

yyaxis left

plot( ...
    true_contrast, ...
    CNR, ...
    '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

ylabel('CNR');
ylim([0 1.8]);

yyaxis right

plot( ...
    true_contrast, ...
    gCNR_direct, ...
    '-s', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

ylabel('Direct-KDE gCNR');
ylim([0 1]);

grid on;
box on;

xlabel('Ground-truth SWS contrast [m/s]');
title('Detectability versus stiffness contrast');

legend( ...
    'CNR', ...
    'Direct-KDE gCNR (exploratory)', ...
    'Location', 'best');

for k = 1:numel(case_names)

    text( ...
        true_contrast(k), ...
        gCNR_direct(k), ...
        ['  ' case_names{k}], ...
        'VerticalAlignment', 'bottom');

end

%% ================================================================
% Figure 3 - Relative bias
% ================================================================

figure;

plot( ...
    true_contrast, ...
    relative_bias, ...
    '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 8);

yline(0, '--');

grid on;
box on;

xlabel('Ground-truth SWS contrast [m/s]');
ylabel('Inclusion relative bias [%]');

title('Quantitative error versus stiffness contrast');

for k = 1:numel(case_names)

    text( ...
        true_contrast(k), ...
        relative_bias(k), ...
        sprintf('  %s (%.1f%%)', ...
        case_names{k}, relative_bias(k)), ...
        'VerticalAlignment', 'bottom');

end

exportgraphics( ...
    gcf, ...
    fullfile(output_dir, ...
    'contrast_sweep_relative_bias.png'), ...
    'Resolution', 300);

%% Summary table

summary_table = table( ...
    case_names.', ...
    c_incl_gt.', ...
    c_incl_est.', ...
    true_contrast.', ...
    relative_bias.', ...
    CNR.', ...
    gCNR_direct.', ...
    'VariableNames', { ...
        'Case', ...
        'GT_Inclusion_SWS_mps', ...
        'Estimated_Inclusion_SWS_mps', ...
        'GT_Contrast_mps', ...
        'RelativeBias_percent', ...
        'CNR', ...
        'DirectKDE_gCNR'});

disp(summary_table);

writetable( ...
    summary_table, ...
    fullfile(output_dir, ...
    'contrast_sweep_metric_summary.csv'));