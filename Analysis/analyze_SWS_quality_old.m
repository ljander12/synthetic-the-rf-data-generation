function results = analyze_SWS_quality(config)

%% ========================================================================
% ANALYZE_SWS_QUALITY
%
% Generic SWS quality analysis for synthetic THE phantoms.
%
% Baseline:
%   original displacement -> phase-gradient SWS
%   Q_C-screened displacement -> phase-gradient SWS
%
% Optional:
%   repeated noisy SWS experiment
%
% ========================================================================


%% ========================================================================
% 1. Configuration
% ========================================================================

Q_threshold = ...
    config.Q_threshold;

filter_speed = ...
    config.sws_filter_speed;

ROI_MARGIN = ...
    config.sws_roi_margin;

IMAGE_MARGIN = ...
    config.sws_image_margin;


fprintf('\n');
fprintf('------------------------------------------------------------\n');
fprintf('SWS QUALITY: %s\n', ...
    upper(config.phantom_case));
fprintf('------------------------------------------------------------\n');


%% ========================================================================
% 2. Make sure k-Wave is available
% ========================================================================

if isempty(which('kWaveGrid'))

    kwave_candidates = ...
        { ...
        fullfile( ...
            getenv('USERPROFILE'), ...
            'Documents', ...
            'MATLAB Add-Ons', ...
            'Collections', ...
            'k-Wave', ...
            'k-Wave'), ...
        fullfile( ...
            getenv('HOME'), ...
            'k-Wave') ...
        };


    for k = 1:numel(kwave_candidates)

        if isfolder(kwave_candidates{k})

            addpath( ...
                genpath( ...
                    kwave_candidates{k}));

        end

    end

end


if isempty(which('kWaveGrid'))

    error( ...
        ['k-Wave was not found. ' ...
         'Add k-Wave to the MATLAB path before SWS analysis.']);

end


%% ========================================================================
% 3. Load dataset
% ========================================================================

data = ...
    load( ...
        config.data_file);


required_variables = ...
    { ...
    'b_data', ...
    'displacement_estimation_autocorr', ...
    'quality_indicator_autocorr', ...
    'shear_params' ...
    };


for k = 1:numel(required_variables)

    if ~isfield(data,required_variables{k})

        error( ...
            'Dataset is missing variable: %s', ...
            required_variables{k});

    end

end


b_data = ...
    data.b_data;


displacement_object = ...
    data.displacement_estimation_autocorr;


quality_indicator = ...
    data.quality_indicator_autocorr;


shear_params = ...
    data.shear_params;


if isfield(data,'prf')

    PRF = ...
        data.prf;

elseif isprop(b_data,'PRF')

    PRF = ...
        b_data.PRF;

else

    error('PRF was not found.');

end


target_frequency = ...
    shear_params.source_freq;


%% ========================================================================
% 4. Autocorrelation parameters
% ========================================================================

if isfield(data,'autocorr_params')

    autocorr_params = ...
        data.autocorr_params;

else

    autocorr_params.z_gate = ...
        4;

    autocorr_params.x_gate = ...
        2;

    autocorr_params.packet_size = ...
        4;

end


%% ========================================================================
% 5. Scan dimensions
% ========================================================================

x_scan = ...
    double( ...
        b_data.scan.x_axis(:).');


z_scan = ...
    double( ...
        b_data.scan.z_axis(:));


[X_scan,Z_scan] = ...
    meshgrid( ...
        x_scan, ...
        z_scan);


Nz = ...
    length(z_scan);


Nx = ...
    length(x_scan);


Nt = ...
    size( ...
        displacement_object.data, ...
        4);


fprintf('Scan:                    %d x %d\n', ...
    Nz, ...
    Nx);


fprintf('Temporal frames:         %d\n', ...
    Nt);


fprintf('Target frequency:        %.1f Hz\n', ...
    target_frequency);


fprintf('Q_C threshold:           %.3f\n', ...
    Q_threshold);


%% ========================================================================
% 6. Extract baseline displacement
% ========================================================================

u_original = ...
    reshape( ...
        double( ...
            displacement_object.data(:,1,1,:)), ...
        Nz, ...
        Nx, ...
        Nt);


u_original = ...
    -u_original;


%% ========================================================================
% 7. Extract C and calculate Q_C
% ========================================================================

C = ...
    reshape( ...
        double( ...
            quality_indicator(:,1,1,:)), ...
        Nz, ...
        Nx, ...
        Nt);


Q_C = ...
    abs( ...
        C - 1);


%% ========================================================================
% 8. Q_C screening
% ========================================================================

[u_screened,QC_baseline] = ...
    apply_QC_screening( ...
        u_original, ...
        Q_C, ...
        Q_threshold);


fprintf('\n');
fprintf('Q_C BASELINE SCREENING\n');
fprintf('------------------------------------------------------------\n');


fprintf('Finite Q_C:              %.2f %%\n', ...
    QC_baseline.finite_percent);


fprintf('Retained finite Q_C:     %.2f %%\n', ...
    QC_baseline.retained_percent);


fprintf('Rejected finite Q_C:     %.2f %%\n', ...
    QC_baseline.rejected_percent);


fprintf('Median Q_C:              %.6f\n', ...
    QC_baseline.median_Q);


%% ========================================================================
% 9. Baseline SWS reconstruction
% ========================================================================

fprintf('\nRunning original baseline SWS...\n');


sws_original = ...
    run_phase_gradient_pipeline( ...
        u_original, ...
        b_data.scan, ...
        PRF, ...
        target_frequency, ...
        filter_speed);


fprintf('Running Q_C-screened baseline SWS...\n');


sws_screened = ...
    run_phase_gradient_pipeline( ...
        u_screened, ...
        b_data.scan, ...
        PRF, ...
        target_frequency, ...
        filter_speed);


%% ========================================================================
% 10. Construct ground-truth material map
% ========================================================================

fprintf('\nConstructing GT material map...\n');


[sws_gt,GT] = ...
    build_GT_SWS_map( ...
        data, ...
        config, ...
        x_scan, ...
        z_scan);


fprintf('GT plane mode:           %d\n', ...
    GT.plane_mode);


fprintf('GT inclusion pixels:     %d\n', ...
    nnz(GT.mask_inclusion_full));


fprintf('GT background pixels:    %d\n', ...
    nnz(GT.mask_background_full));


%% ========================================================================
% 11. Build evaluation ROIs
% ========================================================================

ROI = ...
    build_evaluation_ROIs( ...
        sws_gt, ...
        shear_params.c_shear_incl, ...
        shear_params.c_shear_bkg, ...
        x_scan, ...
        z_scan, ...
        ROI_MARGIN, ...
        IMAGE_MARGIN);


fprintf('\n');
fprintf('Evaluation inclusion core: %d pixels\n', ...
    nnz(ROI.mask_inclusion_core));


fprintf('Evaluation background:     %d pixels\n', ...
    nnz(ROI.mask_background_core));


%% ========================================================================
% 12. Baseline GT evaluation
% ========================================================================

baseline = ...
    evaluate_SWS_pair( ...
        sws_original, ...
        sws_screened, ...
        sws_gt, ...
        ROI, ...
        shear_params.c_shear_incl, ...
        shear_params.c_shear_bkg);


%% ========================================================================
% 13. Print baseline result
% ========================================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('BASELINE SWS QUALITY\n');
fprintf('============================================================\n');


fprintf('\n');
fprintf('                         ORIGINAL      Q_C SCREENED\n');
fprintf('------------------------------------------------------------\n');


fprintf('INCLUSION\n');

fprintf('Mean SWS [m/s]           %8.4f       %8.4f\n', ...
    baseline.original.inclusion_mean, ...
    baseline.screened.inclusion_mean);

fprintf('Bias [m/s]               %8.4f       %8.4f\n', ...
    baseline.original.inclusion_bias, ...
    baseline.screened.inclusion_bias);

fprintf('RMSE [m/s]               %8.4f       %8.4f\n', ...
    baseline.original.inclusion_RMSE, ...
    baseline.screened.inclusion_RMSE);

fprintf('SD [m/s]                 %8.4f       %8.4f\n', ...
    baseline.original.inclusion_std, ...
    baseline.screened.inclusion_std);


fprintf('\nBACKGROUND\n');

fprintf('Mean SWS [m/s]           %8.4f       %8.4f\n', ...
    baseline.original.background_mean, ...
    baseline.screened.background_mean);

fprintf('Bias [m/s]               %8.4f       %8.4f\n', ...
    baseline.original.background_bias, ...
    baseline.screened.background_bias);

fprintf('RMSE [m/s]               %8.4f       %8.4f\n', ...
    baseline.original.background_RMSE, ...
    baseline.screened.background_RMSE);

fprintf('SD [m/s]                 %8.4f       %8.4f\n', ...
    baseline.original.background_std, ...
    baseline.screened.background_std);


fprintf('\nIMAGE QUALITY\n');

fprintf('CNR                       %8.4f       %8.4f\n', ...
    baseline.original.CNR, ...
    baseline.screened.CNR);


fprintf('\nGLOBAL\n');

fprintf('Bias [m/s]               %8.4f       %8.4f\n', ...
    baseline.global_bias_original, ...
    baseline.global_bias_screened);

fprintf('MAE [m/s]                %8.4f       %8.4f\n', ...
    baseline.global_MAE_original, ...
    baseline.global_MAE_screened);

fprintf('RMSE [m/s]               %8.4f       %8.4f\n', ...
    baseline.global_RMSE_original, ...
    baseline.global_RMSE_screened);


fprintf('\nEFFECT OF Q_C SCREENING\n');

fprintf('Inclusion RMSE change:   %+7.2f %%\n', ...
    baseline.inclusion_RMSE_change_percent);

fprintf('Background RMSE change:  %+7.2f %%\n', ...
    baseline.background_RMSE_change_percent);

fprintf('Global RMSE change:      %+7.2f %%\n', ...
    baseline.global_RMSE_change_percent);

fprintf('CNR change:              %+7.2f %%\n', ...
    baseline.CNR_change_percent);


fprintf('============================================================\n');


%% ========================================================================
% 14. Baseline result table
% ========================================================================

baseline_table = ...
    create_SWS_table( ...
        baseline);


%% ========================================================================
% 15. Optional repeated noisy SWS experiment
% ========================================================================

noise = ...
    struct();


noise_table = ...
    table();


if config.run_sws_noise_test

    if ~isfield(data,'channel_data')

        warning( ...
            ['channel_data is not available. ' ...
             'Skipping repeated SWS noise test.']);

    else

        fprintf('\n');
        fprintf('============================================================\n');
        fprintf('REPEATED %d dB SWS TEST\n', ...
            config.sws_noise_dB);
        fprintf('============================================================\n');


        channel_data = ...
            data.channel_data;


        original_b_data = ...
            b_data.data;


        signal_power = ...
            mean( ...
                abs( ...
                    double( ...
                        original_b_data(:))).^2, ...
                'omitnan');


        snr_dB = ...
            config.sws_noise_dB;


        noise_power = ...
            signal_power / ...
            10^(snr_dB/10);


        NR = ...
            config.n_sws_noise_realizations;


        retention = ...
            nan(NR,1);


        median_Q = ...
            nan(NR,1);


        incl_RMSE_original = ...
            nan(NR,1);


        incl_RMSE_screened = ...
            nan(NR,1);


        bkg_RMSE_original = ...
            nan(NR,1);


        bkg_RMSE_screened = ...
            nan(NR,1);


        global_RMSE_original = ...
            nan(NR,1);


        global_RMSE_screened = ...
            nan(NR,1);


        CNR_original = ...
            nan(NR,1);


        CNR_screened = ...
            nan(NR,1);


        for r = 1:NR

            fprintf('\nRealization %d/%d\n', ...
                r, ...
                NR);


            rng( ...
                20000+r, ...
                'twister');


            noise_data = ...
                generate_AWGN( ...
                    original_b_data, ...
                    noise_power);


            b_data.data = ...
                original_b_data + ...
                noise_data;


            estimator = ...
                postprocess.autocorrelation_displacement_estimation();


            estimator.channel_data = ...
                channel_data;


            estimator.input = ...
                b_data;


            estimator.z_gate = ...
                autocorr_params.z_gate;


            estimator.x_gate = ...
                autocorr_params.x_gate;


            estimator.packet_size = ...
                autocorr_params.packet_size;


            displacement_noisy = ...
                estimator.go();


            C_noisy_flat = ...
                estimator.quality_indicator;


            Nt_noisy = ...
                size( ...
                    displacement_noisy.data, ...
                    4);


            u_noisy = ...
                reshape( ...
                    double( ...
                        displacement_noisy.data(:,1,1,:)), ...
                    Nz, ...
                    Nx, ...
                    Nt_noisy);


            u_noisy = ...
                -u_noisy;


            C_noisy = ...
                reshape( ...
                    double( ...
                        C_noisy_flat(:,1,1,:)), ...
                    Nz, ...
                    Nx, ...
                    Nt_noisy);


            Q_noisy = ...
                abs( ...
                    C_noisy - 1);


            [u_noisy_screened,qstats] = ...
                apply_QC_screening( ...
                    u_noisy, ...
                    Q_noisy, ...
                    Q_threshold);


            retention(r) = ...
                qstats.retained_percent;


            median_Q(r) = ...
                qstats.median_Q;


            sws_noisy_original = ...
                run_phase_gradient_pipeline( ...
                    u_noisy, ...
                    b_data.scan, ...
                    PRF, ...
                    target_frequency, ...
                    filter_speed);


            sws_noisy_screened = ...
                run_phase_gradient_pipeline( ...
                    u_noisy_screened, ...
                    b_data.scan, ...
                    PRF, ...
                    target_frequency, ...
                    filter_speed);


            m = ...
                evaluate_SWS_pair( ...
                    sws_noisy_original, ...
                    sws_noisy_screened, ...
                    sws_gt, ...
                    ROI, ...
                    shear_params.c_shear_incl, ...
                    shear_params.c_shear_bkg);


            incl_RMSE_original(r) = ...
                m.original.inclusion_RMSE;


            incl_RMSE_screened(r) = ...
                m.screened.inclusion_RMSE;


            bkg_RMSE_original(r) = ...
                m.original.background_RMSE;


            bkg_RMSE_screened(r) = ...
                m.screened.background_RMSE;


            global_RMSE_original(r) = ...
                m.global_RMSE_original;


            global_RMSE_screened(r) = ...
                m.global_RMSE_screened;


            CNR_original(r) = ...
                m.original.CNR;


            CNR_screened(r) = ...
                m.screened.CNR;


            fprintf( ...
                ['Q %.5f | retained %.2f %% | ' ...
                 'global RMSE %.4f -> %.4f m/s\n'], ...
                median_Q(r), ...
                retention(r), ...
                global_RMSE_original(r), ...
                global_RMSE_screened(r));

        end


        b_data.data = ...
            original_b_data;


        incl_change = ...
            100 * ...
            (incl_RMSE_screened-incl_RMSE_original) ./ ...
            incl_RMSE_original;


        bkg_change = ...
            100 * ...
            (bkg_RMSE_screened-bkg_RMSE_original) ./ ...
            bkg_RMSE_original;


        global_change = ...
            100 * ...
            (global_RMSE_screened-global_RMSE_original) ./ ...
            global_RMSE_original;


        CNR_change = ...
            100 * ...
            (CNR_screened-CNR_original) ./ ...
            CNR_original;


        noise.retained_percent = ...
            retention;


        noise.median_Q = ...
            median_Q;


        noise.inclusion_RMSE_original = ...
            incl_RMSE_original;


        noise.inclusion_RMSE_screened = ...
            incl_RMSE_screened;


        noise.background_RMSE_original = ...
            bkg_RMSE_original;


        noise.background_RMSE_screened = ...
            bkg_RMSE_screened;


        noise.global_RMSE_original = ...
            global_RMSE_original;


        noise.global_RMSE_screened = ...
            global_RMSE_screened;


        noise.CNR_original = ...
            CNR_original;


        noise.CNR_screened = ...
            CNR_screened;


        noise.inclusion_RMSE_change_percent = ...
            incl_change;


        noise.background_RMSE_change_percent = ...
            bkg_change;


        noise.global_RMSE_change_percent = ...
            global_change;


        noise.CNR_change_percent = ...
            CNR_change;


        noise.summary = ...
            struct();


        noise.summary.median_Q_mean = ...
            mean(median_Q);


        noise.summary.median_Q_std = ...
            std(median_Q);


        noise.summary.retained_mean = ...
            mean(retention);


        noise.summary.retained_std = ...
            std(retention);


        noise.summary.inclusion_RMSE_original_mean = ...
            mean(incl_RMSE_original);


        noise.summary.inclusion_RMSE_screened_mean = ...
            mean(incl_RMSE_screened);


        noise.summary.inclusion_change_mean = ...
            mean(incl_change);


        noise.summary.inclusion_change_std = ...
            std(incl_change);


        noise.summary.background_RMSE_original_mean = ...
            mean(bkg_RMSE_original);


        noise.summary.background_RMSE_screened_mean = ...
            mean(bkg_RMSE_screened);


        noise.summary.background_change_mean = ...
            mean(bkg_change);


        noise.summary.background_change_std = ...
            std(bkg_change);


        noise.summary.global_RMSE_original_mean = ...
            mean(global_RMSE_original);


        noise.summary.global_RMSE_screened_mean = ...
            mean(global_RMSE_screened);


        noise.summary.global_change_mean = ...
            mean(global_change);


        noise.summary.global_change_std = ...
            std(global_change);


        noise.summary.CNR_original_mean = ...
            mean(CNR_original);


        noise.summary.CNR_screened_mean = ...
            mean(CNR_screened);


        noise.summary.CNR_change_mean = ...
            mean(CNR_change);


        noise.summary.CNR_change_std = ...
            std(CNR_change);


        fprintf('\n');
        fprintf('============================================================\n');
        fprintf('%d dB REPEATED SWS SUMMARY\n', ...
            snr_dB);
        fprintf('============================================================\n');


        fprintf('Median Q_C:       %.6f +/- %.6f\n', ...
            noise.summary.median_Q_mean, ...
            noise.summary.median_Q_std);


        fprintf('Retained:         %.2f +/- %.2f %%\n', ...
            noise.summary.retained_mean, ...
            noise.summary.retained_std);


        fprintf('\nInclusion RMSE\n');

        fprintf('Original:         %.5f m/s\n', ...
            noise.summary.inclusion_RMSE_original_mean);

        fprintf('Q_C screened:     %.5f m/s\n', ...
            noise.summary.inclusion_RMSE_screened_mean);

        fprintf('Change:           %+.2f +/- %.2f %%\n', ...
            noise.summary.inclusion_change_mean, ...
            noise.summary.inclusion_change_std);


        fprintf('\nBackground RMSE\n');

        fprintf('Original:         %.5f m/s\n', ...
            noise.summary.background_RMSE_original_mean);

        fprintf('Q_C screened:     %.5f m/s\n', ...
            noise.summary.background_RMSE_screened_mean);

        fprintf('Change:           %+.2f +/- %.2f %%\n', ...
            noise.summary.background_change_mean, ...
            noise.summary.background_change_std);


        fprintf('\nGlobal RMSE\n');

        fprintf('Original:         %.5f m/s\n', ...
            noise.summary.global_RMSE_original_mean);

        fprintf('Q_C screened:     %.5f m/s\n', ...
            noise.summary.global_RMSE_screened_mean);

        fprintf('Change:           %+.2f +/- %.2f %%\n', ...
            noise.summary.global_change_mean, ...
            noise.summary.global_change_std);


        fprintf('\nCNR\n');

        fprintf('Original:         %.5f\n', ...
            noise.summary.CNR_original_mean);

        fprintf('Q_C screened:     %.5f\n', ...
            noise.summary.CNR_screened_mean);

        fprintf('Change:           %+.2f +/- %.2f %%\n', ...
            noise.summary.CNR_change_mean, ...
            noise.summary.CNR_change_std);


        Realization = ...
            (1:NR).';


        noise_table = ...
            table( ...
                Realization, ...
                median_Q, ...
                retention, ...
                incl_RMSE_original, ...
                incl_RMSE_screened, ...
                incl_change, ...
                bkg_RMSE_original, ...
                bkg_RMSE_screened, ...
                bkg_change, ...
                global_RMSE_original, ...
                global_RMSE_screened, ...
                global_change, ...
                CNR_original, ...
                CNR_screened, ...
                CNR_change);

    end

end


%% ========================================================================
% 16. Store consolidated results
% ========================================================================

results = ...
    struct();


results.phantom_case = ...
    config.phantom_case;


results.Q_threshold = ...
    Q_threshold;


results.QC_baseline = ...
    QC_baseline;


results.baseline = ...
    baseline;


results.baseline_table = ...
    baseline_table;


results.noise = ...
    noise;


results.noise_table = ...
    noise_table;


results.GT = ...
    GT;


results.ROI_MARGIN = ...
    ROI_MARGIN;


results.IMAGE_MARGIN = ...
    IMAGE_MARGIN;


%% ========================================================================
% 17. Save
% ========================================================================

save_file = ...
    fullfile( ...
        config.results_dir, ...
        sprintf( ...
            '%s_SWS_quality_results.mat', ...
            config.phantom_case));


save( ...
    save_file, ...
    'results', ...
    'sws_original', ...
    'sws_screened', ...
    'sws_gt', ...
    '-v7.3');


baseline_csv = ...
    fullfile( ...
        config.results_dir, ...
        sprintf( ...
            '%s_SWS_baseline.csv', ...
            config.phantom_case));


writetable( ...
    baseline_table, ...
    baseline_csv);


if ~isempty(noise_table)

    noise_csv = ...
        fullfile( ...
            config.results_dir, ...
            sprintf( ...
                '%s_SWS_%ddB_repeated.csv', ...
                config.phantom_case, ...
                config.sws_noise_dB));


    writetable( ...
        noise_table, ...
        noise_csv);

end


fprintf('\nSaved consolidated SWS results:\n');
fprintf('%s\n', ...
    save_file);


%% ========================================================================
% 18. Figures
% ========================================================================

x_mm = ...
    x_scan * 1e3;


z_mm = ...
    z_scan * 1e3;


figure;

imagesc( ...
    x_mm, ...
    z_mm, ...
    sws_gt);

axis image;

set(gca,'YDir','normal');

colorbar;

xlabel('Lateral position [mm]');
ylabel('Depth [mm]');

title( ...
    sprintf( ...
        '%s: ground-truth SWS', ...
        strrep(config.phantom_case,'_',' ')));


figure;

imagesc( ...
    x_mm, ...
    z_mm, ...
    sws_original);

axis image;

set(gca,'YDir','normal');

colorbar;

xlabel('Lateral position [mm]');
ylabel('Depth [mm]');

title( ...
    sprintf( ...
        '%s: original phase-gradient SWS', ...
        strrep(config.phantom_case,'_',' ')));


figure;

imagesc( ...
    x_mm, ...
    z_mm, ...
    sws_screened);

axis image;

set(gca,'YDir','normal');

colorbar;

xlabel('Lateral position [mm]');
ylabel('Depth [mm]');

title( ...
    sprintf( ...
        '%s: Q_C-screened phase-gradient SWS', ...
        strrep(config.phantom_case,'_',' ')));


figure;

imagesc( ...
    x_mm, ...
    z_mm, ...
    sws_screened - ...
    sws_original);

axis image;

set(gca,'YDir','normal');

colorbar;

xlabel('Lateral position [mm]');
ylabel('Depth [mm]');

title( ...
    sprintf( ...
        '%s: screened minus original SWS', ...
        strrep(config.phantom_case,'_',' ')));

end


%% ========================================================================
% LOCAL FUNCTION: Q_C SCREENING
% ========================================================================

function [u_screened,stats] = ...
    apply_QC_screening( ...
        u, ...
        Q_C, ...
        threshold)


valid_Q = ...
    isfinite(Q_C);


accepted = ...
    valid_Q & ...
    Q_C <= threshold;


rejected = ...
    valid_Q & ...
    Q_C > threshold;


u_screened = ...
    u;


u_screened(rejected) = ...
    NaN;


u_screened = ...
    fillmissing( ...
        u_screened, ...
        'linear', ...
        3, ...
        'EndValues', ...
        'nearest');


