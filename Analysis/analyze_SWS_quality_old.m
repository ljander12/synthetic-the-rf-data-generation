%% ========================================================================
% LOCAL FUNCTION: BUILD GT SWS MAP
% ========================================================================

function [sws_gt,GT] = ...
    build_GT_SWS_map( ...
        data, ...
        config, ...
        x_scan, ...
        z_scan)


shear_params = ...
    data.shear_params;


c_incl = ...
    shear_params.c_shear_incl;


[kgrid,medium] = ...
    create_phantom( ...
        shear_params);


if isfield(data,'prb_center') && ...
   isfield(data,'prb_theta')

    prb_center = ...
        double(data.prb_center);


    prb_theta = ...
        double(data.prb_theta);

else

    error( ...
        ['Probe geometry is missing from dataset for ' ...
         config.phantom_case]);

end


[TF,TF_rev] = ...
    coor_transformation( ...
        prb_center, ...
        prb_theta);


origin_col = ...
    [0;0;0;1];


origin_row = ...
    [0 0 0 1];


candidate_origin = ...
    nan(4,3);


tmp = ...
    TF * origin_col;

candidate_origin(1,:) = ...
    tmp(1:3).';


tmp = ...
    origin_row * TF;

candidate_origin(2,:) = ...
    tmp(1:3);


tmp = ...
    TF_rev * origin_col;

candidate_origin(3,:) = ...
    tmp(1:3).';


tmp = ...
    origin_row * TF_rev;

candidate_origin(4,:) = ...
    tmp(1:3);


origin_error = ...
    vecnorm( ...
        candidate_origin - ...
        prb_center(:).', ...
        2, ...
        2);


[~,transform_mode] = ...
    min( ...
        origin_error);


F = ...
    griddedInterpolant( ...
        { ...
        double(kgrid.x_vec(:)), ...
        double(kgrid.y_vec(:)), ...
        double(kgrid.z_vec(:)) ...
        }, ...
        double( ...
            medium.sound_speed_shear), ...
        'nearest', ...
        'none');


[X,Z] = ...
    meshgrid( ...
        x_scan, ...
        z_scan);


N = ...
    numel(X);


local_candidates = ...
    cell(3,1);


local_candidates{1} = ...
    [ ...
    X(:).'; ...
    zeros(1,N); ...
    Z(:).'; ...
    ones(1,N) ...
    ];


local_candidates{2} = ...
    [ ...
    X(:).'; ...
    Z(:).'; ...
    zeros(1,N); ...
    ones(1,N) ...
    ];


local_candidates{3} = ...
    [ ...
    zeros(1,N); ...
    X(:).'; ...
    Z(:).'; ...
    ones(1,N) ...
    ];


candidate_maps = ...
    cell(3,1);


coverage = ...
    zeros(3,1);


inclusion_pixels = ...
    zeros(3,1);


for p = 1:3

    world_h = ...
        apply_transform( ...
            local_candidates{p}, ...
            TF, ...
            TF_rev, ...
            transform_mode);


    values = ...
        F( ...
            world_h(1,:).', ...
            world_h(2,:).', ...
            world_h(3,:).');


    candidate_maps{p} = ...
        reshape( ...
            values, ...
            size(X));


    coverage(p) = ...
        mean( ...
            isfinite( ...
                candidate_maps{p}), ...
            'all');


    inclusion_pixels(p) = ...
        nnz( ...
            abs( ...
                candidate_maps{p} - ...
                c_incl) ...
            < 1e-6);

end


score = ...
    inclusion_pixels;


score(coverage < 0.8) = ...
    -1;


[best_score,plane_mode] = ...
    max(score);


if best_score <= 0

    error( ...
        ['Could not identify inclusion in probe plane for ' ...
         config.phantom_case]);

end


sws_gt = ...
    candidate_maps{plane_mode};


GT = ...
    struct();


GT.transform_mode = ...
    transform_mode;


GT.plane_mode = ...
    plane_mode;


GT.prb_center = ...
    prb_center;


GT.prb_theta = ...
    prb_theta;


GT.coverage = ...
    coverage(plane_mode);


GT.mask_inclusion_full = ...
    isfinite(sws_gt) & ...
    abs( ...
        sws_gt - ...
        shear_params.c_shear_incl) ...
    < 1e-6;


GT.mask_background_full = ...
    isfinite(sws_gt) & ...
    abs( ...
        sws_gt - ...
        shear_params.c_shear_bkg) ...
    < 1e-6;

end


%% ========================================================================
% LOCAL FUNCTION: TRANSFORMATION
% ========================================================================

function world_h = ...
    apply_transform( ...
        local_h, ...
        TF, ...
        TF_rev, ...
        mode)


switch mode

    case 1

        world_h = ...
            TF * ...
            local_h;

    case 2

        world_h = ...
            ( ...
            local_h.' * ...
            TF ...
            ).';

    case 3

        world_h = ...
            TF_rev * ...
            local_h;

    case 4

        world_h = ...
            ( ...
            local_h.' * ...
            TF_rev ...
            ).';

    otherwise

        error('Unknown transform mode.');

end

end


%% ========================================================================
% LOCAL FUNCTION: EVALUATION ROIS
% ========================================================================

function ROI = ...
    build_evaluation_ROIs( ...
        sws_gt, ...
        c_incl, ...
        c_bkg, ...
        x_scan, ...
        z_scan, ...
        ROI_MARGIN, ...
        IMAGE_MARGIN)


mask_inclusion = ...
    isfinite(sws_gt) & ...
    abs(sws_gt-c_incl) < 1e-6;


mask_background = ...
    isfinite(sws_gt) & ...
    abs(sws_gt-c_bkg) < 1e-6;


dx = ...
    median( ...
        diff(x_scan));


dz = ...
    median( ...
        diff(z_scan));


half_x = ...
    max( ...
        1, ...
        ceil( ...
            ROI_MARGIN/dx));


half_z = ...
    max( ...
        1, ...
        ceil( ...
            ROI_MARGIN/dz));


kernel = ...
    ones( ...
        2*half_z+1, ...
        2*half_x+1);


local_inclusion_count = ...
    conv2( ...
        double(mask_inclusion), ...
        kernel, ...
        'same');


mask_inclusion_core = ...
    local_inclusion_count == ...
    numel(kernel);


mask_background_core = ...
    mask_background & ...
    local_inclusion_count == 0;


[X,Z] = ...
    meshgrid( ...
        x_scan, ...
        z_scan);


mask_image_interior = ...
    X >= min(x_scan)+IMAGE_MARGIN & ...
    X <= max(x_scan)-IMAGE_MARGIN & ...
    Z >= min(z_scan)+IMAGE_MARGIN & ...
    Z <= max(z_scan)-IMAGE_MARGIN;


mask_inclusion_core = ...
    mask_inclusion_core & ...
    mask_image_interior;


mask_background_core = ...
    mask_background_core & ...
    mask_image_interior;


ROI = ...
    struct();


ROI.mask_inclusion_full = ...
    mask_inclusion;


ROI.mask_background_full = ...
    mask_background;


ROI.mask_inclusion_core = ...
    mask_inclusion_core;


ROI.mask_background_core = ...
    mask_background_core;


ROI.mask_image_interior = ...
    mask_image_interior;

end


%% ========================================================================
% LOCAL FUNCTION: EVALUATE ORIGINAL VS SCREENED
% ========================================================================

function result = ...
    evaluate_SWS_pair( ...
        sws_original, ...
        sws_screened, ...
        sws_gt, ...
        ROI, ...
        c_incl, ...
        c_bkg)


valid_original = ...
    isfinite(sws_original) & ...
    sws_original > 0 & ...
    sws_original < 10;


valid_screened = ...
    isfinite(sws_screened) & ...
    sws_screened > 0 & ...
    sws_screened < 10;


valid_common = ...
    valid_original & ...
    valid_screened;


mask_inclusion = ...
    ROI.mask_inclusion_core & ...
    valid_common;


mask_background = ...
    ROI.mask_background_core & ...
    valid_common;


global_mask = ...
    ROI.mask_image_interior & ...
    valid_common & ...
    isfinite(sws_gt);


original = ...
    calculate_SWS_metrics( ...
        sws_original, ...
        mask_inclusion, ...
        mask_background, ...
        c_incl, ...
        c_bkg);


screened = ...
    calculate_SWS_metrics( ...
        sws_screened, ...
        mask_inclusion, ...
        mask_background, ...
        c_incl, ...
        c_bkg);


error_original = ...
    sws_original(global_mask) - ...
    sws_gt(global_mask);


error_screened = ...
    sws_screened(global_mask) - ...
    sws_gt(global_mask);


result = ...
    struct();


result.original = ...
    original;


result.screened = ...
    screened;


result.global_bias_original = ...
    mean(error_original);


result.global_bias_screened = ...
    mean(error_screened);


result.global_MAE_original = ...
    mean( ...
        abs(error_original));


result.global_MAE_screened = ...
    mean( ...
        abs(error_screened));


result.global_RMSE_original = ...
    sqrt( ...
        mean( ...
            error_original.^2));


result.global_RMSE_screened = ...
    sqrt( ...
        mean( ...
            error_screened.^2));


result.inclusion_RMSE_change_percent = ...
    100 * ...
    ( ...
    screened.inclusion_RMSE - ...
    original.inclusion_RMSE) ...
    / original.inclusion_RMSE;


result.background_RMSE_change_percent = ...
    100 * ...
    ( ...
    screened.background_RMSE - ...
    original.background_RMSE) ...
    / original.background_RMSE;


result.global_RMSE_change_percent = ...
    100 * ...
    ( ...
    result.global_RMSE_screened - ...
    result.global_RMSE_original) ...
    / result.global_RMSE_original;


result.CNR_change_percent = ...
    100 * ...
    ( ...
    screened.CNR - ...
    original.CNR) ...
    / original.CNR;

end


