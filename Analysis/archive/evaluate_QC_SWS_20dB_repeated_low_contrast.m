function metrics = ...
    calculate_SWS_metrics( ...
        sws, ...
        mask_inclusion, ...
        mask_background, ...
        c_incl, ...
        c_bkg)


    %% --------------------------------------------------------------------
    % Inclusion
    % ---------------------------------------------------------------------

    incl = ...
        double( ...
            sws(mask_inclusion));


    incl = ...
        incl( ...
            isfinite(incl));


    incl_error = ...
        incl - ...
        c_incl;


    metrics.inclusion_mean = ...
        mean(incl);


    metrics.inclusion_median = ...
        median(incl);


    metrics.inclusion_std = ...
        std(incl);


    metrics.inclusion_bias = ...
        mean(incl_error);


    metrics.inclusion_MAE = ...
        mean( ...
            abs(incl_error));


    metrics.inclusion_RMSE = ...
        sqrt( ...
            mean( ...
                incl_error.^2));


    %% --------------------------------------------------------------------
    % Background
    % ---------------------------------------------------------------------

    bkg = ...
        double( ...
            sws(mask_background));


    bkg = ...
        bkg( ...
            isfinite(bkg));


    bkg_error = ...
        bkg - ...
        c_bkg;


    metrics.background_mean = ...
        mean(bkg);


    metrics.background_median = ...
        median(bkg);


    metrics.background_std = ...
        std(bkg);


    metrics.background_bias = ...
        mean(bkg_error);


    metrics.background_MAE = ...
        mean( ...
            abs(bkg_error));


    metrics.background_RMSE = ...
        sqrt( ...
            mean( ...
                bkg_error.^2));


    %% --------------------------------------------------------------------
    % CNR
    % ---------------------------------------------------------------------

    denominator = ...
        sqrt( ...
            metrics.inclusion_std^2 + ...
            metrics.background_std^2);


    if denominator > 0

        metrics.CNR = ...
            abs( ...
                metrics.inclusion_mean - ...
                metrics.background_mean) ...
            / denominator;

    else

        metrics.CNR = ...
            NaN;

    end

end