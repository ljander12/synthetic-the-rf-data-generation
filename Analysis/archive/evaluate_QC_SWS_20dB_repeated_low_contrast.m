    error('Missing file: %s',DATA_FILE);

end


if ~isfile(GT_METRIC_FILE)

    error('Missing file: %s',GT_METRIC_FILE);

end


%% ========================================================================
% 3. Load data
% ========================================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('REPEATED 20 dB Q_C-SCREENED SWS TEST - LOW CONTRAST\n');
fprintf('============================================================\n');


data = ...
    load( ...
        DATA_FILE, ...
        'b_data', ...
        'channel_data', ...
        'shear_params', ...
        'autocorr_params', ...
        'prf');


gt = ...
    load( ...
        GT_METRIC_FILE, ...
        'sws_gt', ...
        'mask_inclusion_core', ...
        'mask_background_core', ...
        'results');


b_data = ...
    data.b_data;


channel_data = ...
    data.channel_data;


shear_params = ...
    data.shear_params;


autocorr_params = ...
    data.autocorr_params;


prf = ...
    data.prf;


sws_gt = ...
    double(gt.sws_gt);


mask_inclusion_core = ...
    logical(gt.mask_inclusion_core);


mask_background_core = ...
    logical(gt.mask_background_core);


%% ========================================================================
% 4. Check loaded UFF objects
% ========================================================================

fprintf('\n');

fprintf('b_data class:       %s\n', ...
    class(b_data));

fprintf('channel_data class: %s\n', ...
    class(channel_data));


if ~isa(b_data,'uff.beamformed_data')

    error('b_data was not loaded correctly.');

end


if ~isa(channel_data,'uff.channel_data')

    error('channel_data was not loaded correctly.');

end


%% ========================================================================
% 5. Experiment parameters
% ========================================================================

SNR_dB = ...
    20;


n_realizations = ...
    10;


Q_threshold = ...
    0.05;


target_frequency = ...
    shear_params.source_freq;


filter_speed = ...
    3.2;


fprintf('\n');

fprintf('SNR:                   %d dB\n', ...
    SNR_dB);

fprintf('Realizations:          %d\n', ...
    n_realizations);

fprintf('Q_C threshold:         %.3f\n', ...
    Q_threshold);

fprintf('Target frequency:      %.1f Hz\n', ...
    target_frequency);


%% ========================================================================
% 6. Scan information
% ========================================================================

x_scan = ...
    double( ...
        b_data.scan.x_axis(:).');


z_scan = ...
    double( ...
        b_data.scan.z_axis(:));


[X_scan, Z_scan] = ...
    meshgrid( ...
        x_scan, ...
        z_scan);


Nz = ...
    length(z_scan);


Nx = ...
    length(x_scan);


fprintf('Scan dimensions:       %d x %d\n', ...
    Nz, ...
    Nx);


%% ========================================================================
% 7. Image-interior mask
% ========================================================================

if isfield(gt.results,'IMAGE_MARGIN')

    IMAGE_MARGIN = ...
        gt.results.IMAGE_MARGIN;

else

    IMAGE_MARGIN = ...
        3e-3;

end


mask_image_interior = ...
    X_scan >= min(x_scan)+IMAGE_MARGIN & ...
    X_scan <= max(x_scan)-IMAGE_MARGIN & ...
    Z_scan >= min(z_scan)+IMAGE_MARGIN & ...
    Z_scan <= max(z_scan)-IMAGE_MARGIN;


%% ========================================================================
% 8. Ground-truth values
% ========================================================================

c_bkg = ...
    double( ...
        shear_params.c_shear_bkg);


c_incl = ...
    double( ...
        shear_params.c_shear_incl);


fprintf('\n');

fprintf('Background GT:         %.3f m/s\n', ...
    c_bkg);

fprintf('Inclusion GT:          %.3f m/s\n', ...
    c_incl);


%% ========================================================================
% 9. Original beamformed signal
% ========================================================================

original_b_data = ...
    b_data.data;


signal_power = ...
    mean( ...
        abs( ...
            double( ...
                original_b_data(:))).^2, ...
        'omitnan');


noise_power = ...
    signal_power / ...
    10^(SNR_dB/10);


fprintf('\n');

fprintf('Signal power:           %.6e\n', ...
    signal_power);

fprintf('Noise power @ 20 dB:   %.6e\n', ...
    noise_power);


%% ========================================================================
% 10. Allocate results
% ========================================================================

retained_percent = ...
    nan(n_realizations,1);


finite_Q_percent = ...
    nan(n_realizations,1);


median_Q = ...
    nan(n_realizations,1);


%% ------------------------------------------------------------------------
% Inclusion
% -------------------------------------------------------------------------

incl_RMSE_original = ...
    nan(n_realizations,1);

incl_RMSE_screened = ...
    nan(n_realizations,1);


incl_bias_original = ...
    nan(n_realizations,1);

incl_bias_screened = ...
    nan(n_realizations,1);


incl_mean_original = ...
    nan(n_realizations,1);

incl_mean_screened = ...
    nan(n_realizations,1);


%% ------------------------------------------------------------------------
% Background
% -------------------------------------------------------------------------

bkg_RMSE_original = ...
    nan(n_realizations,1);

bkg_RMSE_screened = ...
    nan(n_realizations,1);


bkg_bias_original = ...
    nan(n_realizations,1);

bkg_bias_screened = ...
    nan(n_realizations,1);


bkg_mean_original = ...
    nan(n_realizations,1);

bkg_mean_screened = ...
    nan(n_realizations,1);


%% ------------------------------------------------------------------------
% Global
% -------------------------------------------------------------------------

global_RMSE_original = ...
    nan(n_realizations,1);

global_RMSE_screened = ...
    nan(n_realizations,1);


global_MAE_original = ...
    nan(n_realizations,1);

global_MAE_screened = ...
    nan(n_realizations,1);


global_bias_original = ...
    nan(n_realizations,1);

global_bias_screened = ...
    nan(n_realizations,1);


%% ------------------------------------------------------------------------
% CNR
% -------------------------------------------------------------------------

CNR_original = ...
    nan(n_realizations,1);

CNR_screened = ...
    nan(n_realizations,1);


%% ------------------------------------------------------------------------
% Number of valid pixels
% -------------------------------------------------------------------------

N_inclusion = ...
    nan(n_realizations,1);


N_background = ...
    nan(n_realizations,1);


%% ========================================================================
% 11. Main loop
% ========================================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('STARTING 20 dB REALIZATIONS\n');
fprintf('============================================================\n');


for r = 1:n_realizations

    fprintf('\n');
    fprintf('------------------------------------------------------------\n');
    fprintf('REALIZATION %d / %d\n', ...
        r, ...
        n_realizations);
    fprintf('------------------------------------------------------------\n');


    %% ====================================================================
    % 11.1 Reproducible random seed
    % =====================================================================

    seed = ...
        20000 + r;


    rng( ...
        seed, ...
        'twister');


    fprintf('Seed: %d\n', ...
        seed);


    %% ====================================================================
    % 11.2 Generate AWGN
    % =====================================================================

    if isreal(original_b_data)

        noise = ...
            sqrt(noise_power) .* ...
            randn( ...
                size(original_b_data), ...
                'like', ...
                original_b_data);

    else

        noise_real = ...
            randn( ...
                size(original_b_data), ...
                'like', ...
                real(original_b_data));


        noise_imag = ...
            randn( ...
                size(original_b_data), ...
                'like', ...
                real(original_b_data));


        noise = ...
            sqrt(noise_power/2) .* ...
            complex( ...
                noise_real, ...
                noise_imag);

    end


    %% ====================================================================
    % 11.3 Add noise to beamformed data
    % =====================================================================

    b_data.data = ...
        original_b_data + ...
        noise;


    %% ====================================================================
    % 11.4 Run autocorrelation displacement estimator
    % =====================================================================

    displacement_estimator = ...
        postprocess.autocorrelation_displacement_estimation();


    displacement_estimator.channel_data = ...
        channel_data;


    displacement_estimator.input = ...
        b_data;


    displacement_estimator.z_gate = ...
        autocorr_params.z_gate;


    displacement_estimator.x_gate = ...
        autocorr_params.x_gate;


    displacement_estimator.packet_size = ...
        autocorr_params.packet_size;


    displacement_noisy = ...
        displacement_estimator.go();


    C_noisy_flat = ...
        displacement_estimator.quality_indicator;


    %% ====================================================================
    % 11.5 Extract displacement field
    % =====================================================================

    Nt = ...
        size( ...
            displacement_noisy.data, ...
            4);


    u_noisy = ...
        reshape( ...
            double( ...
                displacement_noisy.data(:,1,1,:)), ...
            Nz, ...
            Nx, ...
            Nt);


    %% --------------------------------------------------------------------
    % Same sign convention used in previous analyses
    % ---------------------------------------------------------------------

    u_noisy = ...
        -u_noisy;


    %% ====================================================================
    % 11.6 Extract C and calculate Q_C
    % =====================================================================

    C_noisy = ...
        reshape( ...
            double( ...
                C_noisy_flat(:,1,1,:)), ...
            Nz, ...
            Nx, ...
            Nt);


    Q_C = ...
        abs( ...
            C_noisy - 1);


    valid_Q = ...
        isfinite(Q_C);


    accepted = ...
        valid_Q & ...
        Q_C <= Q_threshold;


    rejected = ...
        valid_Q & ...
        Q_C > Q_threshold;


    finite_Q_percent(r) = ...
        100 * ...
        nnz(valid_Q) / ...
        numel(Q_C);


    retained_percent(r) = ...
        100 * ...
        nnz(accepted) / ...
        nnz(valid_Q);


    median_Q(r) = ...
        median( ...
            Q_C(valid_Q));


    fprintf('Finite Q_C:      %.2f %%\n', ...
        finite_Q_percent(r));


    fprintf('Retained:        %.2f %%\n', ...
        retained_percent(r));


    fprintf('Median Q_C:      %.6f\n', ...
        median_Q(r));


    %% ====================================================================
    % 11.7 Q_C-screened displacement
    % =====================================================================

    u_screened = ...
        u_noisy;


    u_screened(rejected) = ...
        NaN;


    %% --------------------------------------------------------------------
    % Temporal interpolation
    % ---------------------------------------------------------------------

    u_screened = ...
        fillmissing( ...
            u_screened, ...
            'linear', ...
            3, ...
            'EndValues', ...
            'nearest');


    %% --------------------------------------------------------------------
    % Safety fallback
    % ---------------------------------------------------------------------

    remaining_nan = ...
        ~isfinite(u_screened);


    u_screened(remaining_nan) = ...
        u_noisy(remaining_nan);


    fprintf('Remaining NaNs:  %d\n', ...
        nnz(~isfinite(u_screened)));


    %% ====================================================================
    % 11.8 Original noisy SWS reconstruction
    % =====================================================================

    fprintf('Running noisy SWS...\n');


    elasto_original = ...
        run_phase_gradient_pipeline( ...
            u_noisy, ...
            b_data.scan, ...
            prf, ...
            target_frequency, ...
            filter_speed);


    sws_original = ...
        double( ...
            elasto_original.sws_map.u);


    %% ====================================================================
    % 11.9 Q_C-screened SWS reconstruction
    % =====================================================================

    fprintf('Running Q_C-screened SWS...\n');


    elasto_screened = ...
        run_phase_gradient_pipeline( ...
            u_screened, ...
            b_data.scan, ...
            prf, ...
            target_frequency, ...
            filter_speed);


    sws_screened = ...
        double( ...
            elasto_screened.sws_map.u);


    %% ====================================================================
    % 11.10 Common valid SWS pixels
    % =====================================================================

    valid_original = ...
        isfinite(sws_original) & ...
        sws_original > 0 & ...
        sws_original < 10;


    valid_screened = ...
        isfinite(sws_screened) & ...
        sws_screened > 0 & ...
        sws_screened < 10;


    valid_common = ...
        valid_original & ...
        valid_screened;


    inclusion_mask = ...
        mask_inclusion_core & ...
        valid_common;


    background_mask = ...
        mask_background_core & ...
        valid_common;


    global_mask = ...
        mask_image_interior & ...
        valid_common & ...
        isfinite(sws_gt);


    N_inclusion(r) = ...
        nnz(inclusion_mask);


    N_background(r) = ...
        nnz(background_mask);


    if N_inclusion(r) < 20

        error( ...
            'Too few inclusion pixels in realization %d.', ...
            r);

    end


    if N_background(r) < 20

        error( ...
            'Too few background pixels in realization %d.', ...
            r);

    end


    %% ====================================================================
    % 11.11 Region-based metrics
    % =====================================================================

    metrics_orig = ...
        calculate_SWS_metrics( ...
            sws_original, ...
            inclusion_mask, ...
            background_mask, ...
            c_incl, ...
            c_bkg);


    metrics_screen = ...
        calculate_SWS_metrics( ...
            sws_screened, ...
            inclusion_mask, ...
            background_mask, ...
            c_incl, ...
            c_bkg);


    %% --------------------------------------------------------------------
    % Inclusion
    % ---------------------------------------------------------------------

    incl_RMSE_original(r) = ...
        metrics_orig.inclusion_RMSE;


    incl_RMSE_screened(r) = ...
        metrics_screen.inclusion_RMSE;


    incl_bias_original(r) = ...
        metrics_orig.inclusion_bias;


    incl_bias_screened(r) = ...
        metrics_screen.inclusion_bias;


    incl_mean_original(r) = ...
        metrics_orig.inclusion_mean;


    incl_mean_screened(r) = ...
        metrics_screen.inclusion_mean;


    %% --------------------------------------------------------------------
    % Background
    % ---------------------------------------------------------------------

    bkg_RMSE_original(r) = ...
        metrics_orig.background_RMSE;


    bkg_RMSE_screened(r) = ...
        metrics_screen.background_RMSE;


    bkg_bias_original(r) = ...
        metrics_orig.background_bias;


    bkg_bias_screened(r) = ...
        metrics_screen.background_bias;


    bkg_mean_original(r) = ...
        metrics_orig.background_mean;


    bkg_mean_screened(r) = ...
        metrics_screen.background_mean;


    %% --------------------------------------------------------------------
    % CNR
    % ---------------------------------------------------------------------

    CNR_original(r) = ...
        metrics_orig.CNR;


    CNR_screened(r) = ...
        metrics_screen.CNR;


    %% ====================================================================
    % 11.12 Global error
    % =====================================================================

    error_orig = ...
        sws_original(global_mask) - ...
        sws_gt(global_mask);


    error_screen = ...
        sws_screened(global_mask) - ...
        sws_gt(global_mask);


    global_bias_original(r) = ...
        mean(error_orig);


    global_bias_screened(r) = ...
        mean(error_screen);


    global_MAE_original(r) = ...
        mean( ...
            abs(error_orig));


    global_MAE_screened(r) = ...
        mean( ...
            abs(error_screen));


    global_RMSE_original(r) = ...
        sqrt( ...
            mean( ...
                error_orig.^2));


    global_RMSE_screened(r) = ...
        sqrt( ...
            mean( ...
                error_screen.^2));


    %% ====================================================================
    % 11.13 Print realization result
    % =====================================================================

    fprintf('\n');

    fprintf( ...
        'Inclusion RMSE: %.4f -> %.4f m/s\n', ...
        incl_RMSE_original(r), ...
        incl_RMSE_screened(r));


    fprintf( ...
        'Background RMSE: %.4f -> %.4f m/s\n', ...
        bkg_RMSE_original(r), ...
        bkg_RMSE_screened(r));


    fprintf( ...
        'Global RMSE:     %.4f -> %.4f m/s\n', ...
        global_RMSE_original(r), ...
        global_RMSE_screened(r));


    fprintf( ...
        'CNR:             %.4f -> %.4f\n', ...
        CNR_original(r), ...
        CNR_screened(r));


    fprintf( ...
        'Q_C retained:    %.2f %%\n', ...
        retained_percent(r));

end


