%% ========================================================================
% REPEATED 20 dB Q_C-SCREENED SWS TEST - LOW CONTRAST
%
% Purpose:
%
%   Test whether Q_C-based displacement screening improves the final
%   phase-gradient SWS reconstruction under degraded signal conditions.
%
% For each of 10 independent 20 dB noise realizations:
%
%   Original beamformed data
%           ->
%       add AWGN
%           ->
%       autocorrelation displacement
%           ->
%       phase-gradient SWS
%
% and:
%
%       noisy autocorrelation displacement
%           ->
%       Q_C = |C - 1|
%           ->
%       reject Q_C > 0.05
%           ->
%       temporal interpolation
%           ->
%       phase-gradient SWS
%
% Metrics:
%
%   - Inclusion RMSE / bias
%   - Background RMSE / bias
%   - Global RMSE / MAE / bias
%   - CNR
%   - Q_C retention
%   - Median Q_C
%
% NO k-Wave simulation.
% NO Field II simulation.
%
% ========================================================================


