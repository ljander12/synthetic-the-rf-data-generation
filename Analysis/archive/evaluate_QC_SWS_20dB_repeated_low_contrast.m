function elasto = ...
    run_phase_gradient_pipeline( ...
        displacement, ...
        scan, ...
        PRF, ...
        target_frequency, ...
        filter_speed)


    %% --------------------------------------------------------------------
    % Elastography object
    % ---------------------------------------------------------------------

    elasto = ...
        uff.elastography();


    elasto.PRF = ...
        PRF;


    elasto.target_frequency = ...
        target_frequency;


    elasto.scan = ...
        scan;


    %% --------------------------------------------------------------------
    % Displacement field
    % ---------------------------------------------------------------------

    elasto.autocorrelation_field = ...
        uff.data_field();


    elasto.autocorrelation_field.set_component( ...
        'u', ...
        reshape( ...
            displacement, ...
            size(displacement,1), ...
            size(displacement,2), ...
            1, ...
            size(displacement,3)));


    %% --------------------------------------------------------------------
    % Directional filtering
    % ---------------------------------------------------------------------

    num_angles = ...
        12;


    elasto.directional_filtering_angles = ...
        2*pi*linspace( ...
            0, ...
            1-1/num_angles, ...
            num_angles);


    %% --------------------------------------------------------------------
    % Extract target-frequency component
    % ---------------------------------------------------------------------

    extractor = ...
        postprocess.elastography.extract_freq_component( ...
            elasto);


    extractor.target_frequency = ...
        target_frequency;


    extractor.component = ...
        'u';


    extractor.run();


    %% --------------------------------------------------------------------
    % Radial filter
    % ---------------------------------------------------------------------

    omega = ...
        2*pi*target_frequency;


    elasto.radial_filter = ...
        uff.spatial_filter( ...
            'gaussian_charite', ...
            'radial');


    elasto.radial_filter.sigma = ...
        filter_speed / omega;


    %% --------------------------------------------------------------------
    % Angular filter
    % ---------------------------------------------------------------------

    elasto.angular_filter = ...
        uff.spatial_filter( ...
            'gaussian_charite', ...
            'angular');


    elasto.angular_filter.deltaTheta = ...
        median( ...
            diff( ...
                elasto.directional_filtering_angles));


    %% --------------------------------------------------------------------
    % Apply filter
    % ---------------------------------------------------------------------

    filter_operator = ...
        postprocess.elastography.apply_filter( ...
            elasto);


    filter_operator.run();


    %% --------------------------------------------------------------------
    % Phase-gradient method
    % ---------------------------------------------------------------------

    pgm = ...
        postprocess.elastography.phase_gradient_method( ...
            elasto);


    pgm.run();

end


