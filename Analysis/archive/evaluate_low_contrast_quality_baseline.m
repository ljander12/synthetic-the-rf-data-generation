clear;
clc;
close all;

%% ========================================================================
% Evaluate autocorrelation quality metric on low-contrast phantom
%
% Candidate metric:
%
%                       Q_C = |C - 1|
%
% The script:
%   1. Loads displacement estimate, ground truth and C
%   2. Averages ground truth over the autocorrelation packet
%   3. Flips displacement sign to match the GT convention
%   4. Interpolates estimated displacement and C to the GT grid
%   5. Removes a small spatial edge margin
%   6. Computes displacement-error metrics
%   7. Evaluates Q_C against absolute displacement error
%   8. Tests the preliminary threshold Q_C <= 0.05
% ========================================================================


%% ========================================================================
% 1. Load data
% ========================================================================

DATA_FILE = ...
    'low_contrast_displacement_with_quality.mat';

load(DATA_FILE);

fprintf('\n');
fprintf('========================================\n');
fprintf('LOW-CONTRAST QUALITY EVALUATION\n');
fprintf('========================================\n\n');

fprintf('GT size:       %s\n', ...
    mat2str(size(disp_gt)));

fprintf('Estimate size: %s\n', ...
    mat2str(size(displacement_estimation_autocorr.data)));

fprintf('C size:        %s\n\n', ...
    mat2str(size(quality_indicator_autocorr)));


%% ========================================================================
% 2. Autocorrelation packet parameters
% ========================================================================

packet_size = ...
    autocorr_params.packet_size;

packet_intervals = ...
    packet_size - 1;

N_frames = ...
    size(disp_gt,3) - packet_intervals + 1;

fprintf('Packet size:              %d\n', ...
    packet_size);

fprintf('GT intervals per packet:  %d\n', ...
    packet_intervals);

fprintf('Expected output frames:   %d\n\n', ...
    N_frames);


%% ========================================================================
% 3. Average GT displacement over each autocorrelation packet
% ========================================================================
%
% IMPORTANT:
% disp_gt already contains incremental displacement between consecutive
% PRF samples. It must therefore NOT be differentiated again.
%
% A packet_size of 4 RF frames contains 3 displacement intervals.
% ========================================================================

gt_packet = ...
    zeros( ...
        size(disp_gt,1), ...
        size(disp_gt,2), ...
        N_frames);

for k = 1:N_frames

    gt_packet(:,:,k) = ...
        mean( ...
            double( ...
                disp_gt(:,:, ...
                k:k+packet_intervals-1)), ...
            3);

end


%% ========================================================================
% 4. Extract estimated displacement and quality indicator
% ========================================================================

Nz = ...
    length(b_data.scan.z_axis);

Nx = ...
    length(b_data.scan.x_axis);

N_est = ...
    size(displacement_estimation_autocorr.data,4);

if N_est ~= N_frames
    error( ...
        'Estimator has %d frames, expected %d.', ...
        N_est, ...
        N_frames);
end


%% ------------------------------------------------------------------------
% Estimated displacement
% -------------------------------------------------------------------------

disp_est = ...
    reshape( ...
        double( ...
            displacement_estimation_autocorr.data(:,1,1,:)), ...
        Nz, ...
        Nx, ...
        N_est);


%% ------------------------------------------------------------------------
% Flip sign
%
% The autocorrelation estimator uses the opposite displacement sign
% convention relative to the k-Wave ground truth.
% -------------------------------------------------------------------------

disp_est = ...
    -disp_est;


%% ------------------------------------------------------------------------
% Normalized autocorrelation quantity C
% -------------------------------------------------------------------------

C_est = ...
    reshape( ...
        double( ...
            quality_indicator_autocorr(:,1,1,:)), ...
        Nz, ...
        Nx, ...
        N_est);


%% ========================================================================
% 5. Define spatial grids
% ========================================================================

x_est = ...
    double( ...
        b_data.scan.x_axis(:).');

z_est = ...
    double( ...
        b_data.scan.z_axis(:));


%% ------------------------------------------------------------------------
% Ground-truth grid
%
% GT contains 39 lateral samples and 46 axial samples and covers the
% same imaging region as the beamformed scan.
% -------------------------------------------------------------------------

x_gt = ...
    linspace( ...
        x_est(1), ...
        x_est(end), ...
        size(gt_packet,2));

z_gt = ...
    linspace( ...
        z_est(1), ...
        z_est(end), ...
        size(gt_packet,1));


[X_gt, Z_gt] = ...
    meshgrid( ...
        x_gt, ...
        z_gt);


%% ========================================================================
% 6. Interpolate estimate and C to GT grid
% ========================================================================

disp_interp = ...
    nan(size(gt_packet));

C_interp = ...
    nan(size(gt_packet));

for k = 1:N_frames

    disp_interp(:,:,k) = ...
        interp2( ...
            x_est, ...
            z_est, ...
            disp_est(:,:,k), ...
            X_gt, ...
            Z_gt, ...
            'linear', ...
            NaN);

    C_interp(:,:,k) = ...
        interp2( ...
            x_est, ...
            z_est, ...
            C_est(:,:,k), ...
            X_gt, ...
            Z_gt, ...
            'linear', ...
            NaN);

end


%% ========================================================================
% 7. Candidate quality metric
% ========================================================================

Q_C = ...
    abs(C_interp - 1);


%% ========================================================================
% 8. Define valid ROI
% ========================================================================
%
% Remove three samples from each spatial edge to avoid interpolation,
% beamforming and estimator boundary effects.
% ========================================================================

edge_margin = ...
    3;

spatial_mask = ...
    false( ...
        size(gt_packet,1), ...
        size(gt_packet,2));

spatial_mask( ...
    1+edge_margin:end-edge_margin, ...
    1+edge_margin:end-edge_margin) = ...
    true;

spatial_mask_3D = ...
    repmat( ...
        spatial_mask, ...
        1, ...
        1, ...
        N_frames);


%% ------------------------------------------------------------------------
% Finite-data mask
% -------------------------------------------------------------------------

valid_mask = ...
    spatial_mask_3D & ...
    isfinite(gt_packet) & ...
    isfinite(disp_interp) & ...
    isfinite(Q_C);


%% ========================================================================
% 9. Extract valid samples
% ========================================================================

gt_valid = ...
    gt_packet(valid_mask);

est_valid = ...
    disp_interp(valid_mask);

Q_valid = ...
    Q_C(valid_mask);


%% ------------------------------------------------------------------------
% Convert displacement quantities to micrometers
% -------------------------------------------------------------------------

gt_um = ...
    gt_valid * 1e6;

est_um = ...
    est_valid * 1e6;

error_um = ...
    est_um - gt_um;

abs_error_um = ...
    abs(error_um);


%% ========================================================================
% 10. Displacement accuracy metrics
% ========================================================================

N_valid = ...
    numel(error_um);

RMSE_um = ...
    sqrt( ...
        mean(error_um.^2));

MAE_um = ...
    mean(abs_error_um);

median_abs_error_um = ...
    median(abs_error_um);

bias_um = ...
    mean(error_um);


%% ------------------------------------------------------------------------
% Estimate vs GT correlation
% -------------------------------------------------------------------------

corr_est_gt = ...
    corr( ...
        gt_um, ...
        est_um, ...
        'Rows', ...
        'complete');


%% ========================================================================
% 11. Q_C statistics
% ========================================================================

median_Q = ...
    median(Q_valid);

mean_Q = ...
    mean(Q_valid);

P95_Q = ...
    prctile(Q_valid,95);

P99_Q = ...
    prctile(Q_valid,99);


%% ========================================================================
% 12. Association between Q_C and displacement error
% ========================================================================

pearson_Q_error = ...
    corr( ...
        Q_valid, ...
        abs_error_um, ...
        'Type', ...
        'Pearson', ...
        'Rows', ...
        'complete');

spearman_Q_error = ...
    corr( ...
        Q_valid, ...
        abs_error_um, ...
        'Type', ...
        'Spearman', ...
        'Rows', ...
        'complete');


%% ========================================================================
% 13. Preliminary quality threshold
% ========================================================================

Q_threshold = ...
    0.05;

accepted = ...
    Q_valid <= Q_threshold;

rejected = ...
    Q_valid > Q_threshold;


%% ------------------------------------------------------------------------
% Retained samples
% -------------------------------------------------------------------------

retained_fraction = ...
    mean(accepted);

retained_percent = ...
    100 * retained_fraction;


%% ------------------------------------------------------------------------
% Error among retained samples
% -------------------------------------------------------------------------

gated_error_um = ...
    error_um(accepted);

gated_abs_error_um = ...
    abs_error_um(accepted);

gated_RMSE_um = ...
    sqrt( ...
        mean(gated_error_um.^2));

gated_MAE_um = ...
    mean(gated_abs_error_um);

gated_median_error_um = ...
    median(gated_abs_error_um);


%% ------------------------------------------------------------------------
% Error among rejected samples
% -------------------------------------------------------------------------

if any(rejected)

    rejected_error_um = ...
        error_um(rejected);

    rejected_abs_error_um = ...
        abs_error_um(rejected);

    rejected_RMSE_um = ...
        sqrt( ...
            mean(rejected_error_um.^2));

    rejected_median_error_um = ...
        median(rejected_abs_error_um);

else

    rejected_RMSE_um = ...
        NaN;

    rejected_median_error_um = ...
        NaN;

end


%% ========================================================================
% 14. Additional error percentiles
% ========================================================================

P95_error_um = ...
    prctile(abs_error_um,95);

P99_error_um = ...
    prctile(abs_error_um,99);

fraction_gt_1um = ...
    100 * mean(abs_error_um > 1);

fraction_gt_2um = ...
    100 * mean(abs_error_um > 2);

fraction_gt_3um = ...
    100 * mean(abs_error_um > 3);


%% ========================================================================
% 15. Print results
% ========================================================================

fprintf('\n');
fprintf('========================================\n');
fprintf('LOW-CONTRAST BASELINE RESULTS\n');
fprintf('========================================\n');

fprintf('Valid samples:           %d\n\n', ...
    N_valid);

fprintf('DISPLACEMENT ERROR\n');
fprintf('RMSE:                    %.4f um\n', ...
    RMSE_um);

fprintf('MAE:                     %.4f um\n', ...
    MAE_um);

fprintf('Median abs. error:       %.4f um\n', ...
    median_abs_error_um);

fprintf('Bias:                    %.4f um\n', ...
    bias_um);

fprintf('P95 abs. error:          %.4f um\n', ...
    P95_error_um);

fprintf('P99 abs. error:          %.4f um\n', ...
    P99_error_um);

fprintf('Estimate-GT corr.:       %.4f\n\n', ...
    corr_est_gt);


fprintf('ERROR OUTLIERS\n');

fprintf('|error| > 1 um:          %.3f %%\n', ...
    fraction_gt_1um);

fprintf('|error| > 2 um:          %.3f %%\n', ...
    fraction_gt_2um);

fprintf('|error| > 3 um:          %.3f %%\n\n', ...
    fraction_gt_3um);


fprintf('QUALITY METRIC Q_C = |C-1|\n');

fprintf('Median Q_C:              %.6f\n', ...
    median_Q);

fprintf('Mean Q_C:                %.6f\n', ...
    mean_Q);

fprintf('P95 Q_C:                 %.6f\n', ...
    P95_Q);

fprintf('P99 Q_C:                 %.6f\n', ...
    P99_Q);

fprintf('Pearson(Q_C, |error|):   %.4f\n', ...
    pearson_Q_error);

fprintf('Spearman(Q_C, |error|):  %.4f\n\n', ...
    spearman_Q_error);


fprintf('PRELIMINARY THRESHOLD Q_C <= %.3f\n', ...
    Q_threshold);

fprintf('Retained samples:        %.2f %%\n', ...
    retained_percent);

fprintf('RMSE retained:           %.4f um\n', ...
    gated_RMSE_um);

fprintf('MAE retained:            %.4f um\n', ...
    gated_MAE_um);

fprintf('Median error retained:   %.4f um\n', ...
    gated_median_error_um);

fprintf('RMSE rejected:           %.4f um\n', ...
    rejected_RMSE_um);

fprintf('Median error rejected:   %.4f um\n', ...
    rejected_median_error_um);

fprintf('========================================\n\n');


%% ========================================================================
% 16. Scatter plot: Q_C vs absolute displacement error
% ========================================================================

figure;

scatter( ...
    Q_valid, ...
    abs_error_um, ...
    5, ...
    'filled');

xlabel('$Q_C = |C-1|$', ...
    'Interpreter', ...
    'latex');

ylabel('Absolute displacement error [$\mu$m]', ...
    'Interpreter', ...
    'latex');

title('Low-contrast phantom: quality metric vs displacement error');

grid on;


%% ========================================================================
% 17. Threshold comparison
% ========================================================================

figure;

boxchart( ...
    double(accepted), ...
    abs_error_um);

xticks([0 1]);

xticklabels( ...
    {'Rejected', ...
     'Retained'});

ylabel('Absolute displacement error [$\mu$m]', ...
    'Interpreter', ...
    'latex');

title( ...
    sprintf( ...
        'Low-contrast phantom, Q_C threshold = %.2f', ...
        Q_threshold));

grid on;


%% ========================================================================
% 18. Save result summary
% ========================================================================

results = struct();

results.N_valid = ...
    N_valid;

results.RMSE_um = ...
    RMSE_um;

results.MAE_um = ...
    MAE_um;

results.median_abs_error_um = ...
    median_abs_error_um;

results.bias_um = ...
    bias_um;

results.corr_est_gt = ...
    corr_est_gt;

results.median_Q = ...
    median_Q;

results.mean_Q = ...
    mean_Q;

results.pearson_Q_error = ...
    pearson_Q_error;

results.spearman_Q_error = ...
    spearman_Q_error;

results.Q_threshold = ...
    Q_threshold;

results.retained_percent = ...
    retained_percent;

results.gated_RMSE_um = ...
    gated_RMSE_um;

results.gated_MAE_um = ...
    gated_MAE_um;

results.rejected_RMSE_um = ...
    rejected_RMSE_um;


save( ...
    'low_contrast_quality_baseline_results.mat', ...
    'results');


fprintf( ...
    'Results saved to low_contrast_quality_baseline_results.mat\n');