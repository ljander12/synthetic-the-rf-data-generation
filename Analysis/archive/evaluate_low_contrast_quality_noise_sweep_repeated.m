%% ========================================================================
% REPEATED NOISE SWEEP - LOW CONTRAST PHANTOM
%
% Candidate quality metric:
%
%                         Q_C = |C - 1|
%
% Noise levels:
%       baseline, 40, 30, 20, 10 dB
%
% Number of independent noise realizations:
%       10 per non-baseline SNR level
%
% Noise is added to the already beamformed data.
% NO k-Wave or Field II simulation is performed.
% ========================================================================


%% ========================================================================
% 1. Load completed low-contrast dataset
% ========================================================================

DATA_FILE = ...
    'low_contrast_displacement_with_quality.mat';

load(DATA_FILE);

fprintf('\n');
fprintf('=============================================\n');
fprintf('LOW-CONTRAST REPEATED NOISE SWEEP\n');
fprintf('=============================================\n');

fprintf('Beamformed data size: %s\n', ...
    mat2str(size(b_data.data)));

fprintf('GT size:              %s\n', ...
    mat2str(size(disp_gt)));

fprintf('Baseline estimate:    %s\n', ...
    mat2str(size(displacement_estimation_autocorr.data)));

fprintf('=============================================\n\n');


%% ========================================================================
% 2. Experiment parameters
% ========================================================================

snr_levels_dB = ...
    [40 30 20 10];

n_realizations = ...
    10;

Q_threshold = ...
    0.05;

edge_margin = ...
    3;

packet_size = ...
    autocorr_params.packet_size;

packet_intervals = ...
    packet_size - 1;

N_frames = ...
    size(disp_gt,3) - packet_intervals + 1;


%% ========================================================================
% 3. Ground truth packet averaging
% ========================================================================
%
% disp_gt already contains displacement increments between consecutive
% PRF samples.
%
% packet_size = 4 therefore corresponds to 3 GT displacement intervals.
% ========================================================================

gt_packet = ...
    zeros( ...
        size(disp_gt,1), ...
        size(disp_gt,2), ...
        N_frames);

for k = 1:N_frames

    gt_packet(:,:,k) = ...
        mean( ...
            double( ...
                disp_gt(:,:, ...
                k:k+packet_intervals-1)), ...
            3);

end


%% ========================================================================
% 4. Spatial grids
% ========================================================================

Nz = ...
    length(b_data.scan.z_axis);

Nx = ...
    length(b_data.scan.x_axis);

x_est = ...
    double( ...
        b_data.scan.x_axis(:).');

z_est = ...
    double( ...
        b_data.scan.z_axis(:));

x_gt = ...
    linspace( ...
        x_est(1), ...
        x_est(end), ...
        size(gt_packet,2));

z_gt = ...
    linspace( ...
        z_est(1), ...
        z_est(end), ...
        size(gt_packet,1));

[X_gt, Z_gt] = ...
    meshgrid( ...
        x_gt, ...
        z_gt);


%% ========================================================================
% 5. Spatial ROI
% ========================================================================

spatial_mask = ...
    false( ...
        size(gt_packet,1), ...
        size(gt_packet,2));

spatial_mask( ...
    1+edge_margin:end-edge_margin, ...
    1+edge_margin:end-edge_margin) = ...
    true;

spatial_mask_3D = ...
    repmat( ...
        spatial_mask, ...
        1, ...
        1, ...
        N_frames);


%% ========================================================================
% 6. Store original beamformed data
% ========================================================================

original_b_data = ...
    b_data.data;

signal_power = ...
    mean( ...
        abs(double(original_b_data(:))).^2, ...
        'omitnan');

fprintf('Beamformed signal power: %.6e\n\n', ...
    signal_power);


%% ========================================================================
% 7. Metric arrays
% ========================================================================
%
% Rows:
%   1 = baseline
%   2 = 40 dB
%   3 = 30 dB
%   4 = 20 dB
%   5 = 10 dB
%
% Columns = realizations
% ========================================================================

n_conditions = ...
    1 + length(snr_levels_dB);

RMSE_all = ...
    nan(n_conditions,n_realizations);

MAE_all = ...
    nan(n_conditions,n_realizations);

median_error_all = ...
    nan(n_conditions,n_realizations);

corr_all = ...
    nan(n_conditions,n_realizations);

median_Q_all = ...
    nan(n_conditions,n_realizations);

mean_Q_all = ...
    nan(n_conditions,n_realizations);

pearson_all = ...
    nan(n_conditions,n_realizations);

spearman_all = ...
    nan(n_conditions,n_realizations);

gated_RMSE_all = ...
    nan(n_conditions,n_realizations);

gated_MAE_all = ...
    nan(n_conditions,n_realizations);

retained_all = ...
    nan(n_conditions,n_realizations);

outlier_1um_all = ...
    nan(n_conditions,n_realizations);

outlier_2um_all = ...
    nan(n_conditions,n_realizations);

outlier_3um_all = ...
    nan(n_conditions,n_realizations);

seed_matrix = ...
    nan(n_conditions,n_realizations);


%% ========================================================================
% 8. Evaluate baseline
% ========================================================================

fprintf('=============================================\n');
fprintf('EVALUATING BASELINE\n');
fprintf('=============================================\n');

baseline_metrics = ...
    evaluate_quality_run( ...
        displacement_estimation_autocorr, ...
        quality_indicator_autocorr, ...
        gt_packet, ...
        x_est, ...
        z_est, ...
        X_gt, ...
        Z_gt, ...
        spatial_mask_3D, ...
        Nz, ...
        Nx, ...
        Q_threshold);

RMSE_all(1,1) = ...
    baseline_metrics.RMSE_um;

MAE_all(1,1) = ...
    baseline_metrics.MAE_um;

median_error_all(1,1) = ...
    baseline_metrics.median_abs_error_um;

corr_all(1,1) = ...
    baseline_metrics.corr_est_gt;

median_Q_all(1,1) = ...
    baseline_metrics.median_Q;

mean_Q_all(1,1) = ...
    baseline_metrics.mean_Q;

pearson_all(1,1) = ...
    baseline_metrics.pearson_Q_error;

spearman_all(1,1) = ...
    baseline_metrics.spearman_Q_error;

gated_RMSE_all(1,1) = ...
    baseline_metrics.gated_RMSE_um;

gated_MAE_all(1,1) = ...
    baseline_metrics.gated_MAE_um;

retained_all(1,1) = ...
    baseline_metrics.retained_percent;

outlier_1um_all(1,1) = ...
    baseline_metrics.outlier_1um_percent;

outlier_2um_all(1,1) = ...
    baseline_metrics.outlier_2um_percent;

outlier_3um_all(1,1) = ...
    baseline_metrics.outlier_3um_percent;

fprintf( ...
    'Baseline: RMSE = %.4f um, median Q = %.6f, retained = %.2f %%\n\n', ...
    baseline_metrics.RMSE_um, ...
    baseline_metrics.median_Q, ...
    baseline_metrics.retained_percent);


%% ========================================================================
% 9. Repeated noise sweep
% ========================================================================

for s = 1:length(snr_levels_dB)

    snr_dB = ...
        snr_levels_dB(s);

    condition_index = ...
        s + 1;

    fprintf('\n');
    fprintf('=============================================\n');
    fprintf('SNR = %d dB\n', snr_dB);
    fprintf('=============================================\n');

    noise_power = ...
        signal_power / ...
        10^(snr_dB/10);

    for r = 1:n_realizations

        fprintf( ...
            '\nSNR %d dB -- realization %d/%d\n', ...
            snr_dB, ...
            r, ...
            n_realizations);


        %% ----------------------------------------------------------------
        % Reproducible independent random realization
        % -----------------------------------------------------------------

        seed = ...
            1000*s + r;

        seed_matrix(condition_index,r) = ...
            seed;

        rng(seed,'twister');


        %% ----------------------------------------------------------------
        % Generate Gaussian noise
        % -----------------------------------------------------------------

        if isreal(original_b_data)

            noise = ...
                sqrt(noise_power) .* ...
                randn( ...
                    size(original_b_data), ...
                    'like', ...
                    original_b_data);

        else

            noise_real = ...
                randn( ...
                    size(original_b_data), ...
                    'like', ...
                    real(original_b_data));

            noise_imag = ...
                randn( ...
                    size(original_b_data), ...
                    'like', ...
                    real(original_b_data));

            noise = ...
                sqrt(noise_power/2) .* ...
                complex( ...
                    noise_real, ...
                    noise_imag);

        end


        %% ----------------------------------------------------------------
        % Add noise to original beamformed data
        % -----------------------------------------------------------------

        b_data.data = ...
            original_b_data + noise;


        %% ----------------------------------------------------------------
        % Run autocorrelation estimator
        % -----------------------------------------------------------------

        displacement_estimator = ...
            postprocess.autocorrelation_displacement_estimation();

        displacement_estimator.channel_data = ...
            channel_data;

        displacement_estimator.input = ...
            b_data;

        displacement_estimator.z_gate = ...
            autocorr_params.z_gate;

        displacement_estimator.x_gate = ...
            autocorr_params.x_gate;

        displacement_estimator.packet_size = ...
            autocorr_params.packet_size;

        displacement_noisy = ...
            displacement_estimator.go();

        quality_noisy = ...
            displacement_estimator.quality_indicator;


        %% ----------------------------------------------------------------
        % Evaluate current realization
        % -----------------------------------------------------------------

        metrics = ...
            evaluate_quality_run( ...
                displacement_noisy, ...
                quality_noisy, ...
                gt_packet, ...
                x_est, ...
                z_est, ...
                X_gt, ...
                Z_gt, ...
                spatial_mask_3D, ...
                Nz, ...
                Nx, ...
                Q_threshold);


        %% ----------------------------------------------------------------
        % Store metrics
        % -----------------------------------------------------------------

        RMSE_all(condition_index,r) = ...
            metrics.RMSE_um;

        MAE_all(condition_index,r) = ...
            metrics.MAE_um;

        median_error_all(condition_index,r) = ...
            metrics.median_abs_error_um;

        corr_all(condition_index,r) = ...
            metrics.corr_est_gt;

        median_Q_all(condition_index,r) = ...
            metrics.median_Q;

        mean_Q_all(condition_index,r) = ...
            metrics.mean_Q;

        pearson_all(condition_index,r) = ...
            metrics.pearson_Q_error;

        spearman_all(condition_index,r) = ...
            metrics.spearman_Q_error;

        gated_RMSE_all(condition_index,r) = ...
            metrics.gated_RMSE_um;

        gated_MAE_all(condition_index,r) = ...
            metrics.gated_MAE_um;

        retained_all(condition_index,r) = ...
            metrics.retained_percent;

        outlier_1um_all(condition_index,r) = ...
            metrics.outlier_1um_percent;

        outlier_2um_all(condition_index,r) = ...
            metrics.outlier_2um_percent;

        outlier_3um_all(condition_index,r) = ...
            metrics.outlier_3um_percent;


        %% ----------------------------------------------------------------
        % Print realization
        % -----------------------------------------------------------------

        fprintf( ...
            ['RMSE = %.4f um | median Q = %.5f | ' ...
             'Spearman = %.4f | retained = %.2f %% | ' ...
             'gated RMSE = %.4f um\n'], ...
            metrics.RMSE_um, ...
            metrics.median_Q, ...
            metrics.spearman_Q_error, ...
            metrics.retained_percent, ...
            metrics.gated_RMSE_um);

    end

end


