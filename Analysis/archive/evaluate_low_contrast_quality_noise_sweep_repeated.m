%% ========================================================================
% LOCAL FUNCTION
% ========================================================================

function metrics = evaluate_quality_run( ...
    displacement_object, ...
    quality_indicator, ...
    gt_packet, ...
    x_est, ...
    z_est, ...
    X_gt, ...
    Z_gt, ...
    spatial_mask_3D, ...
    Nz, ...
    Nx, ...
    Q_threshold)

    %% --------------------------------------------------------------------
    % Extract displacement
    % ---------------------------------------------------------------------

    N_frames = ...
        size(gt_packet,3);

    disp_est = ...
        reshape( ...
            double( ...
                displacement_object.data(:,1,1,:)), ...
            Nz, ...
            Nx, ...
            N_frames);


    % Autocorrelation estimator has opposite sign convention to GT.

    disp_est = ...
        -disp_est;


    %% --------------------------------------------------------------------
    % Extract C
    % ---------------------------------------------------------------------

    C_est = ...
        reshape( ...
            double( ...
                quality_indicator(:,1,1,:)), ...
            Nz, ...
            Nx, ...
            N_frames);


    %% --------------------------------------------------------------------
    % Interpolate estimate and quality indicator to GT grid
    % ---------------------------------------------------------------------

    disp_interp = ...
        nan(size(gt_packet));

    C_interp = ...
        nan(size(gt_packet));

    for k = 1:N_frames

        disp_interp(:,:,k) = ...
            interp2( ...
                x_est, ...
                z_est, ...
                disp_est(:,:,k), ...
                X_gt, ...
                Z_gt, ...
                'linear', ...
                NaN);

        C_interp(:,:,k) = ...
            interp2( ...
                x_est, ...
                z_est, ...
                C_est(:,:,k), ...
                X_gt, ...
                Z_gt, ...
                'linear', ...
                NaN);

    end


    %% --------------------------------------------------------------------
    % Candidate metric
    % ---------------------------------------------------------------------

    Q_C = ...
        abs(C_interp - 1);


    %% --------------------------------------------------------------------
    % Valid samples
    % ---------------------------------------------------------------------

    valid_mask = ...
        spatial_mask_3D & ...
        isfinite(gt_packet) & ...
        isfinite(disp_interp) & ...
        isfinite(Q_C);

    gt_valid = ...
        gt_packet(valid_mask) .* 1e6;

    est_valid = ...
        disp_interp(valid_mask) .* 1e6;

    Q_valid = ...
        Q_C(valid_mask);


    %% --------------------------------------------------------------------
    % Error
    % ---------------------------------------------------------------------

    error_um = ...
        est_valid - gt_valid;

    abs_error_um = ...
        abs(error_um);


    %% --------------------------------------------------------------------
    % Standard displacement metrics
    % ---------------------------------------------------------------------

    metrics.RMSE_um = ...
        sqrt(mean(error_um.^2));

    metrics.MAE_um = ...
        mean(abs_error_um);

    metrics.median_abs_error_um = ...
        median(abs_error_um);

    metrics.corr_est_gt = ...
        corr( ...
            gt_valid, ...
            est_valid, ...
            'Rows', ...
            'complete');


    %% --------------------------------------------------------------------
    % Q statistics
    % ---------------------------------------------------------------------

    metrics.median_Q = ...
        median(Q_valid);

    metrics.mean_Q = ...
        mean(Q_valid);


    %% --------------------------------------------------------------------
    % Q versus error
    % ---------------------------------------------------------------------

    metrics.pearson_Q_error = ...
        corr( ...
            Q_valid, ...
            abs_error_um, ...
            'Type', ...
            'Pearson', ...
            'Rows', ...
            'complete');

    metrics.spearman_Q_error = ...
        corr( ...
            Q_valid, ...
            abs_error_um, ...
            'Type', ...
            'Spearman', ...
            'Rows', ...
            'complete');


    %% --------------------------------------------------------------------
    % Quality gating
    % ---------------------------------------------------------------------

    accepted = ...
        Q_valid <= Q_threshold;

    metrics.retained_percent = ...
        100 * mean(accepted);

    if any(accepted)

        gated_error = ...
            error_um(accepted);

        metrics.gated_RMSE_um = ...
            sqrt(mean(gated_error.^2));

        metrics.gated_MAE_um = ...
            mean(abs(gated_error));

    else

        metrics.gated_RMSE_um = ...
            NaN;

        metrics.gated_MAE_um = ...
            NaN;

    end


    %% --------------------------------------------------------------------
    % Outlier fractions
    % ---------------------------------------------------------------------

    metrics.outlier_1um_percent = ...
        100 * mean(abs_error_um > 1);

    metrics.outlier_2um_percent = ...
        100 * mean(abs_error_um > 2);

    metrics.outlier_3um_percent = ...
        100 * mean(abs_error_um > 3);

end